type Obj = 'hito' | 'jun' | 'kotoba';
const ASPECT: Record<Obj, ReadingAspect> = { hito: 'character', jun: 'order', kotoba: 'detail' };

interface Q {
  n: string;
  obj: Obj;
  /** 'l' = 聞く（練習）, 'r' = 読む（別例） */
  form: 'l' | 'r';
  prompt: string;
  correct: string;
  wrong: Wrong[];
  h2: string;
  h3: string;
  explain: string;
  at?: ReadingLoc[];
}

/** 段落ごとの文字列を「/」で文に分ける */
const para = (s: string): string[] => s.split('/').map((t) => t.trim());
const passage = (id: string, title: string, paras: string[]): ReadingPassage => ({
  id,
  title,
  genre: 'story',
  paragraphs: paras.map(para),
});

const NTH = ['1', '2', '3', '4', '5', '6'];
function hint1(at: ReadingLoc[]): string {
  const ps = [...new Set(at.map((l) => l.p))];
  const where = ps.map((x) => `${NTH[x - 1]}ばんめ`).join('と ');
  return `${where}の まとまりを もう いちど よもう。`;
}

function makeListen(p: ReadingPassage, q: Q): ListenItem {
  return {
    engine: 'listen',
    id: `${p.id}:${q.n}`,
    objective: q.obj,
    level: 0,
    prompt: `おはなしを きこう。${q.prompt}`,
    audio: [{ text: `${p.title ?? ''}。` }, ...p.paragraphs.map((ps) => ({ text: ps.join('') }))],
    gapMs: 700,
    hideTranscript: true,
    options: opts(q.correct, q.wrong),
    layout: 'column',
    hints: ['「もういちど きく」で、おはなしを もう いちど きいて みよう。', q.h2, q.h3],
    explain: q.explain,
    identity: `folk:${p.id}:${q.n}`,
  };
}

function makeReading(p: ReadingPassage, q: Q): ReadingItem {
  const at = q.at ?? [];
  const paras = [...new Set(at.map((l) => l.p))].map((x) => ({ p: x }));
  return {
    engine: 'reading',
    id: `${p.id}:${q.n}`,
    objective: q.obj,
    level: 1,
    prompt: q.prompt,
    passage: p,
    aspect: ASPECT[q.obj],
    options: opts(q.correct, q.wrong),
    layout: 'column',
    hints: [hint1(at), q.h2, q.h3],
    hintFocus: [paras, at, at],
    evidence: at,
    explain: q.explain,
    identity: `folk:${p.id}:${q.n}`,
    alt: true,
  };
}

