/**
 * g1.ja.read-info せつめいの ぶんを よもう（curriculum-matrix 3.4）。
 * 説明文: 事柄の順序・大事な言葉・問いと答え。本文はすべて本アプリのオリジナル。
 * 同一性キー: 本文ID＋設問（1.4）。
 * 別例（alt）: 説明文以外の文種（ひょう・かんさつの きろく・おしらせ）と、手順のカードを並べる order の問題。
 */
import type { Figure } from '../../engines/figure/types';
import type { OrderItem } from '../../engines/order/order';
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { Item, UnitSpec } from '../../curriculum/types';
import { REVISED, opts, type Wrong } from './util';

type Obj = 'order' | 'word' | 'qa';

interface Q {
  n: string;
  obj: Obj;
  /** 省略時: order → order、word → detail、qa → main-sentence */
  aspect?: ReadingAspect;
  prompt: string;
  correct: string;
  wrong: Wrong[];
  at: ReadingLoc[];
  h2: string;
  h3: string;
  explain: string;
}

const DEFAULT_ASPECT: Record<Obj, ReadingAspect> = {
  order: 'order',
  word: 'detail',
  qa: 'main-sentence',
};

const CIRCLED = '①②③④⑤⑥';

function hint1(p: ReadingPassage, at: ReadingLoc[]): string {
  const ps = [...new Set(at.map((l) => l.p))];
  if (p.numbered) return `${ps.map((x) => CIRCLED[x - 1]).join('と ')}の だんらくを よもう。`;
  if (p.genre === 'chart') return 'ひょうの 中《なか》を よく 見《み》よう。';
  return `${ps.map((x) => `${x}ばんめ`).join('と ')}の まとまりを よもう。`;
}

function make(p: ReadingPassage, q: Q, alt: boolean): ReadingItem {
  const paras = [...new Set(q.at.map((l) => l.p))].map((x) => ({ p: x }));
  return {
    engine: 'reading',
    id: `${p.id}:${q.n}`,
    objective: q.obj,
    level: alt ? 1 : 0,
    prompt: q.prompt,
    passage: p,
    aspect: q.aspect ?? DEFAULT_ASPECT[q.obj],
    options: opts(q.correct, q.wrong),
    hints: [hint1(p, q.at), q.h2, q.h3],
    hintFocus: [paras, q.at, q.at],
    evidence: q.at,
    explain: q.explain,
    identity: `info:${p.id}:${q.n}`,
    alt,
  };
}

