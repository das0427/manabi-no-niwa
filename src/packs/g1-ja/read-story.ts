/**
 * g1.ja.read-story おはなしを よもう（curriculum-matrix 3.4）。
 * 物語: 場面の様子・人物の行動・時間の順序。答えの根拠の文は evidence（正答で下線）と hintFocus（ヒントで囲む）。
 *
 * 本文はすべて本アプリのオリジナル。「おむすび ころりん」だけは、作者不詳の伝承の昔話（鼠浄土）を
 * 本アプリが自分の文で再話したもの。
 * 同一性キー: 本文ID＋設問（1.4。同じ本文の同じ設問の言い換えは同じ）。
 * 別例（alt）: 物語以外の文種（し・てがみ・えにっき）の本文と、文カードを並べる order の問題。
 */
import type { Figure } from '../../engines/figure/types';
import type { OrderItem } from '../../engines/order/order';
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { Item, UnitSpec } from '../../curriculum/types';
import { REVISED, opts, type Wrong } from './util';

type Obj = 'scene' | 'character' | 'order';

const ASPECT: Record<Obj, ReadingAspect> = {
  scene: 'detail',
  character: 'character',
  order: 'order',
};

interface Q {
  n: string;
  obj: Obj;
  prompt: string;
  correct: string;
  wrong: Wrong[];
  /** 根拠の文 */
  at: ReadingLoc[];
  /** ヒント②（根拠の文を囲む）と③（最後の一手を残す） */
  h2: string;
  h3: string;
  explain: string;
}

const NTH = ['1', '2', '3', '4', '5', '6'];

function hint1(p: ReadingPassage, at: ReadingLoc[]): string {
  const ps = [...new Set(at.map((l) => l.p))];
  const where = ps.map((x) => `${NTH[x - 1]}ばんめ`).join('と ');
  const unit = p.genre === 'poem' ? 'まとまり（れん）' : 'まとまり';
  return `${where}の ${unit}を もう いちど よもう。`;
}

function make(p: ReadingPassage, q: Q, alt: boolean): ReadingItem {
  const paras = [...new Set(q.at.map((l) => l.p))].map((x) => ({ p: x }));
  return {
    engine: 'reading',
    id: `${p.id}:${q.n}`,
    objective: q.obj,
    level: alt ? 1 : 0,
    prompt: q.prompt,
    passage: p,
    aspect: ASPECT[q.obj],
    options: opts(q.correct, q.wrong),
    hints: [hint1(p, q.at), q.h2, q.h3],
    hintFocus: [paras, q.at, q.at],
    evidence: q.at,
    explain: q.explain,
    identity: `story:${p.id}:${q.n}`,
    alt,
  };
}

