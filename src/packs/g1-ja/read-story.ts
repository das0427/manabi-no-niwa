/** 本文を図に（order の問題で、本文を見ながら並べられるように） */
const passageFig = (p: ReadingPassage): Figure => ({
  kind: 'column',
  gap: 1,
  items: p.paragraphs.map((para) => ({ kind: 'text', text: para.join(''), size: 'm' })),
});

function orderItem(
  p: ReadingPassage,
  cards: string[],
  hints: [string, string, string],
  explain: string,
): OrderItem {
  return {
    engine: 'order',
    id: `${p.id}:order-cards`,
    objective: 'order',
    level: 1,
    prompt: `「${p.title ?? ''}」の おはなしの じゅんに、文《ぶん》の カードを ならべよう。`,
    figure: passageFig(p),
    cards: cards.map((label) => ({ label })),
    layout: 'column',
    ends: ['はじめ', 'おわり'],
    reverseMisconception: OR,
    hints,
    explain,
    identity: `story:${p.id}:order-cards`,
    alt: true,
  };
}

