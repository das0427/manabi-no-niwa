function toOptions(os: Opt[]): ChoiceOption[] {
  return os.map((o) => ({
    label: o.label,
    ...(o.illust ? { figure: { kind: 'illust' as const, id: o.illust } } : {}),
    ...(o.correct ? { correct: true } : {}),
    ...(o.mis ? { misconception: o.mis } : {}),
  }));
}

