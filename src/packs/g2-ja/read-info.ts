/**
 * g2.ja.read-info せつめいの 文を 読もう（curriculum-matrix 3.5）。
 * 説明文: 順序の言葉・重要な文（問い・まとめ）・大事な言葉と図（グラフ・きろく）・つくりかたの手順。
 *
 * 本文はすべて本アプリのオリジナル。説明文6本（うち つくりかた2本）＋ 図表つき2本・観察の記録1本。
 * 同一性キー: 本文ID × 設問（1.4）。手順を並べる order の問題は、表し方を変えた問題（alt）。
 * 段階: 0 = 順序・大事な言葉（説明文）、1 = 重要な文・つくりかた（説明文）、2 = 図表・記録・並べ替えで確かめる（alt）。
 */
import type { OrderItem } from '../../engines/order/order';
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { Item, UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'order' | 'main' | 'detail' | 'steps';

interface Q {
  o: Obj;
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h2: string;
  h3: string;
  /** 根拠の場所（空なら図・表が根拠） */
  f: ReadingLoc[];
  e: string;
  h1?: string;
  aspect?: ReadingAspect;
}

const CIRCLED = '①②③④⑤⑥⑦⑧⑨';
const DEFAULT_ASPECT: Record<Obj, ReadingAspect> = {
  order: 'order',
  main: 'main-sentence',
  detail: 'detail',
  steps: 'order',
};

function build(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  return qs.map((x) => {
    const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
    const h1 =
      x.h1 ??
      (p.numbered
        ? `${paras.map((l) => CIRCLED[l.p - 1]).join('と ')}の だんらくを 読《よ》もう。`
        : `${paras.map((l) => `${l.p}つめ`).join('と ')}の まとまりを 読《よ》もう。`);
    const level = alt ? 2 : x.o === 'order' || x.o === 'detail' ? 0 : 1;
    const has = x.f.length > 0;
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level,
      aspect: x.aspect ?? DEFAULT_ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: has ? [paras, x.f, x.f] : [null, null, null],
      ...(has ? { evidence: x.f } : {}),
      explain: x.e,
      identity: `info:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

