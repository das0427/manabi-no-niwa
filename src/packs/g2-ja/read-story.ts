/**
 * g2.ja.read-story おはなしを 読もう（curriculum-matrix 3.5）。
 * 物語: 場面の様子（様子の言葉）・人物の行動・行動の理由・気持ち。自分の体験と結ぶ「かいてみよう」（採点しない）。
 *
 * 本文はすべて本アプリのオリジナル（再話なし）。物語6本＋別の文種（手紙・日記・詩）3本。
 * 同一性キー: 本文ID × 設問（同じ本文の同じ設問の言い換えは同じ: 1.4）。
 * 段階: 0 = 様子・人物（物語）、1 = 理由・気持ち（物語）、2 = 別の文種で確かめる（alt）。
 */
import type { ExplainItem } from '../../engines/explain/explain';
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { Item, UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'detail' | 'character' | 'reason' | 'feeling';

const ASPECT: Record<Obj, ReadingAspect> = {
  detail: 'detail',
  character: 'character',
  reason: 'reason',
  feeling: 'feeling',
};

interface Q {
  o: Obj;
  /** 設問の名前（同一性キー） */
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h2: string;
  h3: string;
  /** 根拠の場所（ヒント②③で囲み、正答で下線） */
  f: ReadingLoc[];
  e: string;
  h1?: string;
}

const ORD = ['1つめ', '2つめ', '3つめ', '4つめ', '5つめ', '6つめ'];

function build(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  return qs.map((x) => {
    const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
    const h1 = x.h1 ?? `${paras.map((l) => ORD[l.p - 1]).join('と ')}の まとまりを 読《よ》もう。`;
    const level = alt ? 2 : x.o === 'detail' || x.o === 'character' ? 0 : 1;
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level,
      aspect: ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: [paras, x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `story:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

