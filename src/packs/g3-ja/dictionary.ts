/**
 * g3.ja.dictionary 国語辞典の使い方（curriculum-matrix 3.6）。
 * 五十音順に並べる（1字目 → 2字目以降）→ 清音・濁音・半濁音と のばす音「ー」の並び方 → 見出し語（言い切りの形）で引く。
 *
 * 並べ方の規則（多くの国語辞典に共通の扱いだけを問う）:
 * - 1字目から順にくらべ、同じなら次の字をくらべる。短い語が長い語の頭と同じなら、短い語が先。
 * - 濁音・半濁音は、まず清音と同じとみてくらべ、それでも同じときだけ 清音 → 濁音 → 半濁音 の順。
 * - のばす音「ー」は、前の音の母音（ボール → ぼおる）に読みかえる。
 * 辞典によって扱いが分かれる並べ方（小さい「っ」「ゃ」と大きい字の前後、カタカナとひらがなの前後）は問題にしない。
 *
 * 同一性キー: 語の組（並べ替え）・問いの語（選択）ごと。
 */
import type { ChoiceItem, Item, OrderItem, UnitSpec } from '../../curriculum/types';
import { opts, REVISED, type Wrong } from './util';

const ENDS: [string, string] = ['先《さき》', 'あと'];

// ---- 1. 五十音順（1字目・2字目以降） ----
interface OrderQ {
  k: string;
  /** 正しい順の語 */
  words: string[];
  h1: string;
  h2: string;
  h3: string;
  e: string;
  wrong?: { order: number[]; misconception: string }[];
}

function orderItem(obj: string, level: number, q: OrderQ): OrderItem {
  return {
    engine: 'order',
    id: `${obj}:${q.k}`,
    objective: obj,
    level,
    prompt: '国語《こくご》じてんに のって いる じゅんに ならべよう。',
    cards: q.words.map((label) => ({ label })),
    ends: ENDS,
    reverseMisconception: 'd-reverse',
    ...(q.wrong ? { wrongOrders: q.wrong } : {}),
    hints: [q.h1, q.h2, q.h3],
    explain: `${q.words.join(' → ')} の じゅんです。${q.e}`,
    identity: `dict:${obj}:${q.k}`,
  };
}

