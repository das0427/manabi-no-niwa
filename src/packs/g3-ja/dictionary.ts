// ---- 選択の問題（別例・見出し語） ----
interface ChoiceQ {
  obj: string;
  level: number;
  k: string;
  q: string;
  c: string;
  w: Wrong[];
  h: [string, string, string];
  e: string;
  alt?: boolean;
}

function choiceItem(x: ChoiceQ): ChoiceItem {
  return {
    engine: 'choice',
    id: `${x.obj}:${x.k}`,
    objective: x.obj,
    level: x.level,
    prompt: x.q,
    options: opts(x.c, x.w),
    hints: x.h,
    explain: x.e,
    identity: `dict:${x.obj}:${x.k}`,
    ...(x.alt ? { alt: true } : {}),
  };
}

