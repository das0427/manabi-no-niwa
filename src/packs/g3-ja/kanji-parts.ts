function findItem(f: Find): ChoiceItem {
  return {
    engine: 'choice',
    id: `find:${f.k}`,
    objective: 'find',
    level: 0,
    prompt: `この字《じ》の${WHERE[f.where]}の部分《ぶぶん》の名前《なまえ》はどれ？`,
    figure: { kind: 'text', text: f.ch, size: 'xl' },
    options: opts(f.c, f.w),
    hints: [`字《じ》の${WHERE[f.where]}だけを見《み》よう。`, f.h2, f.h3],
    explain: f.e,
    identity: `parts:find:${f.k}`,
  };
}

