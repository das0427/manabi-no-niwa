function buildItem(b: Build): BuildItem {
  return {
    engine: 'build',
    id: `build:${b.k}`,
    objective: 'build',
    level: 1,
    prompt: `「${b.s}」の ふとい 字《じ》の ところを 漢字《かんじ》で 書《か》くよ。その 漢字《かんじ》を 作《つく》る 部分《ぶぶん》を 2つ えらぼう。`,
    tiles: b.tiles,
    answer: { kind: 'parts', parts: b.parts },
    // 誤答の例は、タイルの文（よみ付き）を '+' でつなぐ（文の検査で よみの無い漢字にしない）
    wrongAnswers: b.wrong.map((w) => ({
      value: w
        .split('+')
        .map((p) => b.tiles.find((t) => t.startsWith(`${p}《`)) ?? p)
        .join('+'),
      misconception: 'k-similar-part',
    })),
    hints: [b.h1, b.h2, b.h3],
    explain: b.e,
    identity: `parts:build:${b.k}`,
  };
}

