function findItem(f: Find): ChoiceItem {
  return {
    engine: 'choice',
    id: `find:${f.k}`,
    objective: 'find',
    level: 0,
    prompt: `この 字《じ》の ${WHERE[f.where]}の 部分《ぶぶん》の 名前《なまえ》は どれ？`,
    figure: { kind: 'text', text: f.ch, size: 'xl' },
    options: opts(f.c, f.w),
    hints: [`字《じ》の ${WHERE[f.where]}だけを 見《み》よう。`, f.h2, f.h3],
    explain: f.e,
    identity: `parts:find:${f.k}`,
  };
}

