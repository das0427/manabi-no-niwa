interface Q {
  talk: TalkId;
  ok: string;
  wrong: Wrong[];
  h2: string;
  h3: string;
  e: string;
  /** memo の図（メモ） */
  memo?: string;
}

/** 練習の問題 */
function practice(obj: Obj, q: Q): ListenItem {
  return {
    engine: 'listen',
    id: `${obj}:${q.talk}`,
    objective: obj,
    level: LV[obj],
    prompt: PROMPT[obj],
    audio: { text: TALKS[q.talk] },
    ...(q.memo ? { figure: { kind: 'text' as const, text: q.memo, size: 'm' as const } } : {}),
    options: opts(q.ok, q.wrong),
    layout: 'column',
    hints: [H1[obj], q.h2, q.h3],
    explain: q.e,
    identity: `lm:${obj}:${q.talk}`,
  };
}

/** 別例（選択肢が文のもの） */
function altText(obj: Obj, prompt: string, q: Q): ListenItem {
  return {
    engine: 'listen',
    id: `${obj}-alt:${q.talk}`,
    objective: obj,
    level: LV[obj],
    alt: true,
    prompt,
    audio: { text: TALKS[q.talk] },
    options: opts(q.ok, q.wrong),
    layout: 'column',
    hints: [H1[obj], q.h2, q.h3],
    explain: q.e,
    identity: `lm:${obj}-alt:${q.talk}`,
  };
}

