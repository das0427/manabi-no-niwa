const BY_ID = new Map(P.map((p) => [p.id, p]));
const get = (id: string): Proverb => {
  const p = BY_ID.get(id);
  if (!p) throw new Error(`proverbs: ${id} が無い`);
  return p;
};
/** id ならそのことわざの文、そうでなければ文のまま */
const textOf = (x: string) => BY_ID.get(x)?.t ?? x;
/** id ならそのことわざの意味、そうでなければ文のまま */
const meaningOf = (x: string) => BY_ID.get(x)?.m ?? x;

// ---- 1. 意味（choice） ----
function meaningItem(p: Proverb): ChoiceItem {
  return {
    engine: 'choice',
    id: `meaning:${p.id}`,
    objective: 'meaning',
    level: 0,
    prompt: `「${p.t}」の 意味《いみ》は どれ？`,
    options: opts(`${p.m}。`, [
      [`${p.lit}。`, 'p-literal'],
      [`${meaningOf(p.other[0])}。`, p.other[1]],
    ]),
    layout: 'column',
    hints: [
      'ことわざは、たとえを 使《つか》って 生活《せいかつ》の 知《し》えを 教《おし》えて いるよ。字《じ》の とおりの 意味《いみ》では ないよ。',
      p.clue,
      'その たとえを、人《ひと》の 生活《せいかつ》に あてはめると どう なるかな。',
    ],
    explain: `「${p.t}」は、${p.m}と いう 意味《いみ》です。${p.clue}`,
    identity: `proverb:${p.id}:meaning`,
  };
}

