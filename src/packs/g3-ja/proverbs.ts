function matchItem(ids: string[], gi: number): MatchItem {
  const ps = ids.map(get);
  // 下の段は意味の順を1つずらして書く（画面でも混ぜる）
  const right = ps.map((_, i) => ps[(i + 1) % ps.length]!.short);
  return {
    engine: 'match',
    id: `match:${gi + 1}`,
    objective: 'meaning',
    level: 0,
    prompt: 'ことわざと意味《いみ》を線《せん》でむすぼう。',
    left: ps.map((p) => ({ label: p.t })),
    right: right.map((label) => ({ label })),
    pairs: ps.map((_, i) => [i, (i - 1 + ps.length) % ps.length] as [number, number]),
    hints: [
      'わかることわざからむすんでいこう。',
      'ことわざのたとえを思《おも》い出《だ》そう。（さるなら木《き》のぼり、など）',
      'のこったものどうしをむすぼう。',
    ],
    explain: ps.map((p) => `「${p.t}」は「${p.short}」。`).join(''),
    identity: `proverb:match:${ids.join('+')}`,
    alt: true,
  };
}

