/**
 * g3.ja.read-character 登場人物の気持ち（curriculum-matrix 3.6）。
 * 物語: 気持ちを表す言葉・ようす → 気持ちが変わったきっかけ → はじめと終わりの気持ちの比べ → 行動・会話から性格。
 *
 * 本文はすべて本アプリのオリジナル（再話なし）。物語6本＋別の文種（日記・手紙・詩）3本。
 * 教科書の定番教材の題材・構成（夜に勇気を出す話・戦争の話 など）は使わない。
 * 同一性キー: 本文ID × 設問（同じ本文の同じ設問の言い換えは同じ: 1.4）。
 * 段階: 0 = 気持ちの言葉、1 = きっかけ・変化、2 = 性格、3 = 別の文種で確かめる（alt）。
 */
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'word' | 'trigger' | 'change' | 'nature';

const ASPECT: Record<Obj, ReadingAspect> = {
  word: 'feeling',
  trigger: 'reason',
  change: 'feeling',
  nature: 'character',
};

const LEVEL: Record<Obj, number> = { word: 0, trigger: 1, change: 1, nature: 2 };

interface Q {
  o: Obj;
  /** 設問の名前（同一性キー） */
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h2: string;
  h3: string;
  /** 根拠の場所（ヒント②③で囲み、正答で下線） */
  f: ReadingLoc[];
  e: string;
  h1?: string;
}

function placeName(p: ReadingPassage, n: number): string {
  return p.genre === 'poem' ? `${n}つ目《め》のまとまり` : `${n}だんらく目《め》`;
}

function build(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  return qs.map((x) => {
    const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
    const h1 = x.h1 ?? `${paras.map((l) => placeName(p, l.p)).join('と')}を読《よ》もう。`;
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level: alt ? 3 : LEVEL[x.o],
      aspect: ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: [paras, x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `character:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

