/**
 * g3.ja.read-paragraphs だんらくの 役わり（curriculum-matrix 3.6）。
 * 説明文: 段落の役割（問い・答え・まとめ）と、段落どうしの関係（れい・つけたし・じゅんじょ）。
 * 導→基→応: 段落の番号と役割 → 問いの段落と答えの段落・関係 → 段落を並べ替える（order）。
 *
 * 本文はすべて本アプリのオリジナル（教科書の定番教材の題材・構成を使わない）。
 * 説明文6本（練習）＋ 記録文2本・図表つき1本（別例 alt）。並べ替えは説明の短文6本（練習）＋記録・報告3本（alt）。
 * 同一性キー: 本文ID × 設問（同じ本文の同じ設問の言い換えは同じ: 1.4）／並べ替えは短文ごと。
 * 段階: 0 = 問い・まとめの段落、1 = 答えの段落・段落の関係、2 = 段落を並べ替える、3 = 別の文種で確かめる（alt）。
 *
 * 段落を答える問題では、ヒントで答えの段落だけを囲まない（候補の段落をまとめて囲む）。
 */
import type { OrderItem } from '../../engines/order/order';
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { Item, UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'question' | 'answer' | 'summary' | 'relation' | 'arrange';

interface Q {
  o: Exclude<Obj, 'arrange'>;
  /** 設問の名前（同一性キー） */
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h1?: string;
  h2: string;
  h3: string;
  /** 答えの根拠の場所（正答で下線） */
  f: ReadingLoc[];
  /** ヒント②③で囲む場所（答えの段落だけにならないよう、候補をまとめて書く）。省略時は f */
  foc?: ReadingLoc[];
  /** 解説 */
  e: string;
}

const CIRCLED = '①②③④⑤⑥⑦⑧⑨';
/** 段落の選択肢の文 */
const P = (n: number) => `${CIRCLED[n - 1]}の だんらく`;
/** 段落全体の場所の列 */
const ps = (...n: number[]): ReadingLoc[] => n.map((p) => ({ p }));

const ASPECT: Record<Q['o'], ReadingAspect> = {
  question: 'main-sentence',
  answer: 'detail',
  summary: 'main-sentence',
  relation: 'order',
};

const H1: Record<Q['o'], string> = {
  question: '「〜でしょうか」のように、たずねて いる 文《ぶん》を さがそう。',
  answer:
    '問《と》いの 文《ぶん》を もう 一度《いちど》 読《よ》んで、何《なに》を たずねて いるか たしかめよう。',
  summary:
    '「このように」「〜ことが わかりました」のような、まとめる ことばに 目《め》を つけよう。',
  relation:
    'それぞれの だんらくが 何《なに》に ついて 書《か》いて いるか、はじめの 文《ぶん》を 読《よ》もう。',
};

function build(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  return qs.map((x) => {
    const level = alt ? 3 : x.o === 'question' || x.o === 'summary' ? 0 : 1;
    const foc = x.foc ?? x.f;
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level,
      aspect: ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [x.h1 ?? H1[x.o], x.h2, x.h3],
      hintFocus: [null, foc, foc],
      evidence: x.f,
      explain: x.e,
      identity: `para:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

