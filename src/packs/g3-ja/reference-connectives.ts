function ksdItem(x: Ksd): FillItem {
  const ans = x.set[x.k]!;
  return {
    engine: 'fill',
    id: `kosoado:${x.id}`,
    objective: 'kosoado',
    level: 0,
    prompt: '場面《ばめん》に合《あ》うこそあど言葉《ことば》をえらぼう。',
    text: x.text,
    options: x.set,
    blanks: [
      {
        answers: [ans],
        wrong: x.set
          .filter((_, i) => i !== x.k)
          .map((value) => ({ value, misconception: 'rc-kosoado' })),
      },
    ],
    hints: [
      '（）の中《なか》の、場面《ばめん》のせつめいをよく読《よ》もう。',
      'さすものは、話《はな》す人《ひと》の近《ちか》く？聞《き》く人《ひと》の近《ちか》く？どちらからも遠《とお》い？それともたずねている？',
      `この場面《ばめん》は「${KIND_WHY[x.k]}」ときだね。「こ・そ・あ・ど」のどれを使《つか》うかな。`,
    ],
    explain: `「${KIND_WHY[x.k]}」ときには「${KIND[x.k]}」ではじまる言葉《ことば》を使《つか》うので、「${ans}」です。`,
    identity: `kosoado:${x.id}`,
  };
}

/** 別例: はたらきから えらぶ */
function ksdRuleItem(k: number): ChoiceItem {
  return {
    engine: 'choice',
    id: `kosoado:rule:${KIND[k]}`,
    objective: 'kosoado',
    level: 0,
    prompt: `${KIND_WHY[k]}ときに使《つか》う言葉《ことば》はどれですか。`,
    // これ・それ・あれ・どれ の 順に 固定して、正解の 場所を 問いごとに かえる
    options: SET_THING.map((label, i) =>
      i === k ? { label, correct: true } : { label, misconception: 'rc-kosoado' },
    ),
    fixedOrder: true,
    hints: [
      '「こ・そ・あ・ど」の四《よっ》つのなかまを思《おも》い出《だ》そう。',
      'ものが話《はな》す人《ひと》・聞《き》く人《ひと》のどちらのそばにあるか、どちらからも遠《とお》いかで言葉《ことば》がかわるよ。',
      '自分《じぶん》の手《て》の上《うえ》・友《とも》だちの手《て》の上《うえ》・遠《とお》くの山《やま》をゆびさす場面《ばめん》を思《おも》いうかべて、それぞれ何《なん》と言《い》うか考《かんが》えよう。',
    ],
    explain: `${KIND_WHY[k]}ときには「${SET_THING[k]}」（${KIND[k]}）を使《つか》います。こ＝話《はな》す人《ひと》の近《ちか》く、そ＝聞《き》く人《ひと》の近《ちか》く、あ＝どちらからも遠《とお》い、ど＝たずねるです。`,
    identity: `kosoado:rule:${KIND[k]}`,
    alt: true,
  };
}

