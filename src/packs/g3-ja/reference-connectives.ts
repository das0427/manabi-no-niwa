function shijiItem(s: Shiji): ChoiceItem {
  return {
    engine: 'choice',
    id: `shiji:${s.id}`,
    objective: 'shiji',
    level: 0,
    prompt: `「${s.word}」は 何《なに》を さして いますか。`,
    figure: { kind: 'text', text: s.text, size: 'm' },
    options: opts(s.ans, s.w),
    layout: 'column',
    hints: [
      `こそあど言葉《ことば》が さす ものは、ふつう「${s.word}」より 前《まえ》に 書《か》いて あるよ。`,
      s.h2,
      s.h3,
    ],
    explain: s.e,
    identity: `shiji:${s.id}`,
  };
}

