// ---- 4. 短い 文章で（reading。別例） ----
interface RQ {
  o: 'shiji' | 'setsuzoku';
  k: string;
  q: string;
  c: string;
  w: Wrong[];
  h2: string;
  h3: string;
  f: ReadingLoc[];
  e: string;
}

function readingItems(p: ReadingPassage, qs: RQ[]): ReadingItem[] {
  return qs.map((x) => {
    const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level: x.o === 'shiji' ? 0 : 1,
      aspect: x.o === 'shiji' ? 'detail' : 'reason',
      passage: p,
      prompt: x.q,
      options: opts(x.c, x.w),
      hints: [
        x.o === 'shiji'
          ? 'こそあど言葉《ことば》のすぐ前《まえ》の文《ぶん》を読《よ》もう。'
          : '（）の前《まえ》の文《ぶん》と後《うし》ろの文《ぶん》を読《よ》みくらべよう。',
        x.h2,
        x.h3,
      ],
      hintFocus: [paras, x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `read:${p.id}:${x.k}`,
      alt: true,
    };
  });
}

