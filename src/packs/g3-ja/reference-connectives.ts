function ksdItem(x: Ksd): FillItem {
  const ans = x.set[x.k]!;
  return {
    engine: 'fill',
    id: `kosoado:${x.id}`,
    objective: 'kosoado',
    level: 0,
    prompt: '場面《ばめん》に 合《あ》う こそあど言葉《ことば》を えらぼう。',
    text: x.text,
    options: x.set,
    blanks: [
      {
        answers: [ans],
        wrong: x.set
          .filter((_, i) => i !== x.k)
          .map((value) => ({ value, misconception: 'rc-kosoado' })),
      },
    ],
    hints: [
      '（ ）の 中《なか》の、場面《ばめん》の せつめいを よく 読《よ》もう。',
      'さす ものは、話《はな》す 人《ひと》の 近《ちか》く？ 聞《き》く 人《ひと》の 近《ちか》く？ どちらからも 遠《とお》い？ それとも たずねて いる？',
      `この 場面《ばめん》は「${KIND_WHY[x.k]}」ときだね。こ・そ・あ・ど の どれを 使《つか》うかな。`,
    ],
    explain: `「${KIND_WHY[x.k]}」ものには「${KIND[x.k]}」で はじまる 言葉《ことば》を 使《つか》うので、「${ans}」です。`,
    identity: `kosoado:${x.id}`,
  };
}

/** 別例: はたらきから えらぶ */
function ksdRuleItem(k: number): ChoiceItem {
  return {
    engine: 'choice',
    id: `kosoado:rule:${KIND[k]}`,
    objective: 'kosoado',
    level: 0,
    prompt: `${KIND_WHY[k]} ものを さす ときに 使《つか》う 言葉《ことば》は どれですか。`,
    options: opts(
      SET_THING[k]!,
      SET_THING.filter((_, i) => i !== k).map((w) => [w, 'rc-kosoado'] as const),
    ),
    fixedOrder: true,
    hints: [
      'こ・そ・あ・ど の 四《よっ》つの なかまを 思《おも》い出《だ》そう。',
      '「こ」は 自分《じぶん》の 近《ちか》く、「そ」は 相手《あいて》の 近《ちか》く だよ。',
      '「あ」は どちらからも 遠《とお》い もの、「ど」は たずねる ときに 使《つか》うよ。',
    ],
    explain: `${KIND_WHY[k]} ものには「${SET_THING[k]}」（${KIND[k]}）を 使《つか》います。こ＝話《はな》す 人《ひと》の 近《ちか》く、そ＝聞《き》く 人《ひと》の 近《ちか》く、あ＝どちらからも 遠《とお》い、ど＝たずねる です。`,
    identity: `kosoado:rule:${KIND[k]}`,
    alt: true,
  };
}

