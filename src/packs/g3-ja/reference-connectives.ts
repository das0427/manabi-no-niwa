function shijiItem(s: Shiji): ChoiceItem {
  return {
    engine: 'choice',
    id: `shiji:${s.id}`,
    objective: 'shiji',
    level: 0,
    prompt: `「${s.word}」は何《なに》をさしていますか。`,
    figure: { kind: 'text', text: s.text, size: 'm' },
    options: opts(s.ans, s.w),
    layout: 'column',
    hints: [
      `こそあど言葉《ことば》がさすものは、ふつう「${s.word}」より前《まえ》に書《か》いてあるよ。`,
      s.h2,
      s.h3,
    ],
    explain: s.e,
    identity: `shiji:${s.id}`,
  };
}

