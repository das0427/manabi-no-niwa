const CONJ_HINT: Record<Conj, string> = {
  なぜなら: 'あとの文《ぶん》は「〜からです」で終《お》わっているね。',
  たとえば:
    'あとの文《ぶん》は、前《まえ》の文《ぶん》のことをじっさいのものをあげて言《い》っているね。',
  このように: 'あとの文《ぶん》は、前《まえ》に書《か》いたことをまとめているね。',
};

function wrongConj(ok: Conj, w: Conj): string {
  if (ok === 'このように' || w === 'このように') return 'conj-summary';
  return 'conj-reason-example';
}

function tsunagiItem([t, ok]: (typeof TSUNAGI)[number]): FillItem {
  const wrongs = CONJ.filter((c) => c !== ok);
  return {
    engine: 'fill',
    id: `tsunagi:${t}`,
    objective: 'tsunagi',
    level: 1,
    prompt: 'あいているところに入《はい》るつなぎ言葉《ことば》をえらぼう。',
    text: t,
    options: [...CONJ],
    blanks: [
      {
        answers: [ok],
        wrong: wrongs.map((w) => ({ value: w, misconception: wrongConj(ok, w) })),
      },
    ],
    hints: [
      'あいているところの前《まえ》の文《ぶん》とあとの文《ぶん》のつながりを考《かんが》えよう。',
      CONJ_HINT[ok],
      'えらんだ言葉《ことば》をあいているところに入《い》れて、声《こえ》に出《だ》して読《よ》んでみよう。つながりがしぜんかな。',
    ],
    explain: `${t.replace('{{}}', `**${ok}**`)}「${ok}」でつなぐと、文《ぶん》のつながりがよく分《わ》かります。`,
    identity: `tsunagi:${t}`,
  };
}

