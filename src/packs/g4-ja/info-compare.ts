function bunruiItem(b: Bunrui): SortItem {
  return {
    engine: 'sort',
    id: `bunrui:${b.id}`,
    objective: 'bunrui',
    level: 1,
    prompt: `「${b.kanten}」と いう 観点《かんてん》で、二《ふた》つに 分《わ》けよう。`,
    boxes: b.boxes.map((label) => ({ label })),
    cards: b.cards.map(([label, box, shift]) => ({
      label,
      box,
      ...(shift ? { wrongBoxes: [{ box: 1 - box, misconception: 'viewpoint-shift' }] } : {}),
    })),
    hints: [
      `観点《かんてん》は「${b.kanten}」だけ。ほかの ことは 考《かんが》えないよ。`,
      '一《ひと》つ 分《わ》けるたびに、「この 観点《かんてん》で 見《み》て いるかな」と たしかめよう。',
      'なかまの 名前《なまえ》や 形《かたち》など、べつの 観点《かんてん》に 目《め》が うつって いないか 見直《みなお》そう。',
    ],
    explain: b.e,
    identity: `bunrui:${b.id}`,
  };
}

