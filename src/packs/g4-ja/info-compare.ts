function hyouItem(h: Hyou): ChoiceItem {
  return {
    engine: 'choice',
    id: `hikaku:${h.id}`,
    objective: 'hikaku',
    level: 0,
    layout: 'column',
    prompt: `表《ひょう》を見《み》てくらべよう。${ASK_TEXT[h.ask]}`,
    figure: { kind: 'table', header: ['', h.a, h.b], rows: h.rows },
    options: opts(h.ok, [
      [h.mix, 'same-diff-mix'],
      [h.out, 'not-in-source'],
    ]),
    hints: [
      '表《ひょう》の行《ぎょう》を一《ひと》つずつ、左《ひだり》と右《みぎ》でくらべよう。',
      h.ask === 'same'
        ? '左《ひだり》と右《みぎ》に同《おな》じことが書《か》いてある行《ぎょう》をさがそう。'
        : '左《ひだり》と右《みぎ》でちがうことが書《か》いてある行《ぎょう》をさがそう。',
      '表《ひょう》に書《か》いていないことは、答《こた》えにならないよ。',
    ],
    explain: h.e,
    identity: `hikaku:${h.id}`,
  };
}

