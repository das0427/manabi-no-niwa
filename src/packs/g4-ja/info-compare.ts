function hyouItem(h: Hyou): ChoiceItem {
  return {
    engine: 'choice',
    id: `hikaku:${h.id}`,
    objective: 'hikaku',
    level: 0,
    layout: 'column',
    prompt: `表《ひょう》を 見《み》て くらべよう。${ASK_TEXT[h.ask]}`,
    figure: { kind: 'table', header: ['', h.a, h.b], rows: h.rows },
    options: opts(h.ok, [
      [h.mix, 'same-diff-mix'],
      [h.out, 'not-in-source'],
    ]),
    hints: [
      '表《ひょう》の 行《ぎょう》を 一《ひと》つずつ、左《ひだり》と 右《みぎ》で くらべよう。',
      h.ask === 'same'
        ? '左《ひだり》と 右《みぎ》に 同《おな》じ ことが 書《か》いて ある 行《ぎょう》を さがそう。'
        : '左《ひだり》と 右《みぎ》で ちがう ことが 書《か》いて ある 行《ぎょう》を さがそう。',
      '表《ひょう》に 書《か》いて いない ことは、答《こた》えに ならないよ。',
    ],
    explain: h.e,
    identity: `hikaku:${h.id}`,
  };
}

