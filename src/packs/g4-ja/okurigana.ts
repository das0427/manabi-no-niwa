function wordItem(w: Word): ChoiceItem {
  return {
    engine: 'choice',
    id: `word:${w.id}`,
    objective: 'choose',
    level: 0,
    prompt: `「${w.kana}」を漢字《かんじ》と送《おく》りがなで書《か》くと、どれですか。`,
    options: opts(w.ok, w.wrong),
    layout: 'column',
    hints: [H1, H2[w.cat], w.h3],
    explain: w.e,
    identity: `okuri:word:${w.id}`,
  };
}

