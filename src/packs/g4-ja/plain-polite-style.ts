function unifyItem(u: Unify): FillItem {
  return {
    engine: 'fill',
    id: `soroe:${u.id}`,
    objective: 'unify',
    level: 1,
    prompt: '文末《ぶんまつ》がそろうように、{{}}に入《はい》ることばをえらぼう。',
    text: u.text,
    options: [u.ok, ...u.wrong.map(([v]) => v)],
    blanks: [
      {
        answers: [u.ok],
        wrong: u.wrong.map(([value, misconception]) => ({ value, misconception })),
      },
    ],
    hints: [
      '空《あ》いていないほうの文《ぶん》の終《お》わりを見《み》よう。',
      'その文《ぶん》は、です・ますかな。だ・であるかな。',
      u.polite
        ? 'です・ますの文章《ぶんしょう》だね。同《おな》じなかまの形《かたち》をえらぼう。'
        : 'だ・であるの文章《ぶんしょう》だね。「です」「ます」をつけない形《かたち》で、自然《しぜん》に言《い》えるものをえらぼう。',
    ],
    explain: u.e,
    identity: `pp:soroe:${u.id}`,
  };
}

