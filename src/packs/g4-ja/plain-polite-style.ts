function unifyItem(u: Unify): FillItem {
  return {
    engine: 'fill',
    id: `soroe:${u.id}`,
    objective: 'unify',
    level: 1,
    prompt: '文末《ぶんまつ》が そろうように、{{}}に 入《はい》る ことばを えらぼう。',
    text: u.text,
    options: [u.ok, ...u.wrong.map(([v]) => v)],
    blanks: [
      {
        answers: [u.ok],
        wrong: u.wrong.map(([value, misconception]) => ({ value, misconception })),
      },
    ],
    hints: [
      '空《あ》いて いない ほうの 文《ぶん》の 終《お》わりを 見《み》よう。',
      'その 文《ぶん》は、です・ますかな。だ・であるかな。',
      u.polite
        ? 'です・ますの 文章《ぶんしょう》だね。同《おな》じ なかまの 形《かたち》を えらぼう。'
        : 'だ・であるの 文章《ぶんしょう》だね。「です」「ます」を つけない 形《かたち》で、自然《しぜん》に 言《い》える ものを えらぼう。',
    ],
    explain: u.e,
    identity: `pp:soroe:${u.id}`,
  };
}

