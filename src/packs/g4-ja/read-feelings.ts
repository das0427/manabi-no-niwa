/**
 * g4.ja.read-feelings 気持ちの変化とじょうけい（curriculum-matrix 3.7）。
 * 物語: じょうけい（景色や天気・音などの様子）の文を見つける → 人物の気持ちと結び付ける →
 * 気持ちの変化（はじめ → 終わり）→ 変化のきっかけ。
 *
 * 本文はすべて本アプリのオリジナル（再話なし）。物語6本＋別の文種（詩・日記・手紙）3本。
 * 同一性キー: 本文ID × 設問（同じ本文の同じ設問の言い換えは同じ: 1.4）。
 * 段階: 0 = じょうけい・結び付き（物語）、1 = 変化・きっかけ（物語）、2 = 別の文種で確かめる（alt）。
 */
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'scene' | 'link' | 'change' | 'reason';

const ASPECT: Record<Obj, ReadingAspect> = {
  scene: 'detail',
  link: 'feeling',
  change: 'feeling',
  reason: 'reason',
};

interface Q {
  o: Obj;
  /** 設問の名前（同一性キー） */
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h2: string;
  h3: string;
  /** 根拠の場所（ヒント②③で囲み、正答で下線） */
  f: ReadingLoc[];
  e: string;
  h1?: string;
}

const ORD = ['1つめ', '2つめ', '3つめ', '4つめ', '5つめ', '6つめ', '7つめ'];

function build(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  const unit = p.genre === 'poem' ? 'れん' : 'だんらく';
  return qs.map((x) => {
    const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
    const h1 =
      x.h1 ?? `${paras.map((l) => ORD[l.p - 1]).join('と')}の${unit}を読《よ》み返《かえ》そう。`;
    const level = alt ? 2 : x.o === 'scene' || x.o === 'link' ? 0 : 1;
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level,
      aspect: ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: [paras, x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `feel:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

