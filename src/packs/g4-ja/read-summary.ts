/**
 * g4.ja.read-summary 中心の 文と 要約（curriculum-matrix 3.7）。
 * 説明文: だんらくの中心となる文を選ぶ → 中心となる言葉を選ぶ → 要約として合うもの・要約に使う文を選ぶ → 要約の文を並べる（order）。
 *
 * 本文はすべて本アプリのオリジナル。説明文6本（段階0・1）＋ 図表つき2本・観察の記録1本（段階2、alt）。
 * 教科書の定番教材の題材（ウナギ・和紙・工芸品・もんしろちょう・和室と洋室 など）は使わない。
 * 図表の数は本アプリの例示データ（実在の調査ではない）。
 * 同一性キー: 本文ID × 設問（1.4）。要約の文を並べる order は、本文ID ごとに1問。
 */
import type { OrderItem } from '../../engines/order/order';
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { Item, UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'center' | 'keyword' | 'summary' | 'arrange';

const ASPECT: Record<Exclude<Obj, 'arrange'>, ReadingAspect> = {
  center: 'main-sentence',
  keyword: 'main-sentence',
  summary: 'gist',
};

interface Q {
  o: Exclude<Obj, 'arrange'>;
  /** 設問の名前（同一性キー） */
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h2: string;
  h3: string;
  /** 根拠の場所（ヒント②③で囲み、正答で下線） */
  f: ReadingLoc[];
  e: string;
  h1?: string;
}

const CIRCLED = '①②③④⑤⑥⑦⑧⑨';

function build(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  return qs.map((x) => {
    const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
    const h1 =
      x.h1 ?? `${paras.map((l) => CIRCLED[l.p - 1]).join('と ')}のだんらくを読《よ》もう。`;
    const level = alt ? 2 : x.o === 'summary' ? 1 : 0;
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level,
      aspect: ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: [paras, x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `summary:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

/** 要約の文を並べる（cards は正しい順） */
function arrange(
  p: ReadingPassage,
  cards: string[],
  wrong: number[],
  hints: [string, string, string],
  explain: string,
  alt: boolean,
): OrderItem {
  return {
    engine: 'order',
    id: `${p.id}:narabe`,
    objective: 'arrange',
    level: alt ? 2 : 1,
    prompt: `「${p.title ?? ''}」の要約《ようやく》になるように、文《ぶん》をならべよう。`,
    layout: 'column',
    cards: cards.map((label) => ({ label })),
    ends: ['はじめ', 'おわり'],
    reverseMisconception: 's-order-swap',
    wrongOrders: [{ order: wrong, misconception: 's-order-swap' }],
    hints,
    explain,
    identity: `summary:${p.id}:narabe`,
    ...(alt ? { alt: true } : {}),
  };
}

