// ---- 1. 報告の 型に 分ける ----
function kataItem(r: Report): SortItem {
  return {
    engine: 'sort',
    id: `kata:${r.id}`,
    objective: 'kata',
    level: 0,
    prompt: `「${r.title}」の ほうこくの 文《ぶん》を、四《よっ》つの まとまりに 分《わ》けよう。`,
    boxes: PARTS.map((label) => ({ label })),
    cards: [
      {
        label: r.kikkake,
        box: 0,
        wrongBoxes: [{ box: 1, misconception: 'method-reason' }],
      },
      {
        label: r.shirabe,
        box: 1,
        wrongBoxes: [
          { box: 0, misconception: 'method-reason' },
          { box: 2, misconception: 'method-reason' },
        ],
      },
      ...r.wakatta.map((label) => ({
        label,
        box: 2,
        wrongBoxes: [{ box: 3, misconception: 'fact-opinion' }],
      })),
      {
        label: r.kangae,
        box: 3,
        wrongBoxes: [{ box: 2, misconception: 'fact-opinion' }],
      },
    ],
    hints: [
      'きっかけは「なぜ 調《しら》べようと 思《おも》ったか」、調《しら》べ方《かた》は「どうやって 調《しら》べたか」だよ。',
      '分《わ》かった ことは、調《しら》べて 分《わ》かった 事実《じじつ》。「〜そうです」「〜でした」の 文《ぶん》が 多《おお》いよ。',
      '考《かんが》えた ことは 自分《じぶん》の 考《かんが》え。「〜と 考《かんが》えます」「〜と 思《おも》います」の 文《ぶん》だよ。',
    ],
    explain: `きっかけ「${r.kikkake}」、調《しら》べ方《かた》「${r.shirabe}」、考《かんが》えた こと「${r.kangae}」。のこりの 二《ふた》つが 分《わ》かった ことです。`,
    identity: `kata:${r.id}`,
  };
}

