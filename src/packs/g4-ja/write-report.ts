function junItem(r: Report): OrderItem {
  return {
    engine: 'order',
    id: `jun:${r.id}`,
    objective: 'jun',
    level: 1,
    layout: 'column',
    prompt: `「${r.title}」の ほうこくの だんらくを、正《ただ》しい じゅんに ならべよう。`,
    cards: [r.kikkake, r.shirabe, r.wakatta.join(''), r.kangae].map((label) => ({ label })),
    ends: ['はじめ', 'おわり'],
    reverseMisconception: 'report-order',
    wrongOrders: [
      { order: [0, 2, 1, 3], misconception: 'report-order' },
      { order: [0, 1, 3, 2], misconception: 'fact-opinion' },
      { order: [1, 0, 2, 3], misconception: 'method-reason' },
    ],
    hints: [
      'ほうこくは、「なぜ 調《しら》べたか」から 書《か》き始《はじ》めるよ。',
      'どうやって 調《しら》べたかを 書《か》いてから、分《わ》かった ことを 書《か》くよ。',
      '自分《じぶん》の 考《かんが》えは、分《わ》かった ことの あと、さいごに 書《か》くよ。',
    ],
    explain:
      'きっかけ → 調《しら》べ方《かた》 → 分《わ》かった こと → 考《かんが》えた こと の じゅんです。分《わ》かった ことを もとに 考《かんが》えを 書《か》くので、考《かんが》えは さいごです。',
    identity: `jun:${r.id}`,
  };
}

/** 別例: 次に書くまとまりを選ぶ */
function junAlt(i: number): ChoiceItem {
  const next = i + 1;
  const wrongs = [0, 1, 2, 3]
    .filter((k) => k !== i && k !== next)
    .map((k) => [PARTS[k]!, 'report-order'] as const);
  return {
    engine: 'choice',
    id: `jun-alt:${i}`,
    objective: 'jun',
    level: 1,
    alt: true,
    prompt: `ほうこくで「${PARTS[i]}」の だんらくの 次《つぎ》に 書《か》く だんらくは どれ？`,
    options: opts(PARTS[next]!, wrongs),
    hints: [
      'ほうこくの 四《よっ》つの まとまりの じゅんを 思《おも》い出《だ》そう。',
      'はじめは きっかけ、さいごは 自分《じぶん》の 考《かんが》えだよ。',
      '調《しら》べた 中身《なかみ》は、調《しら》べ方《かた》の あとに 書《か》くよ。',
    ],
    explain: `「${PARTS[i]}」の 次《つぎ》は「${PARTS[next]}」です。きっかけ → 調《しら》べ方《かた》 → 分《わ》かった こと → 考《かんが》えた こと の じゅんに 書《か》きます。`,
    identity: `jun-alt:${i}`,
  };
}

