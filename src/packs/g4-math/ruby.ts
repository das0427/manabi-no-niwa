/** 見出し → よみ付きの語（長い見出しが先） */
const DICT: [string, string][] = WORDS.split(/\s+/)
  .filter((w) => w)
  .map((w) => [w.replace(/《[^》]*》/g, ''), w] as [string, string])
  .sort((a, b) => b[0].length - a[0].length);

/** 辞書に無かった漢字（検査用。テストと補助スクリプトが見る） */
export const MISSING = new Map<string, string>();
/** 辞書の語が 漢字どうしで つながった 所（「図《ず》書《か》館」のような 読みの まちがいを 見つけるため） */
export const JOINED = new Map<string, string>();

const RUBY_RUN = /[一-鿿㐀-䶿々〆ヶ]+《[^》]*》/y;

/** 文に《よみ》を付ける */
export function R(s: string, extra: readonly [string, string][] = []): string {
  if (!/[一-鿿]/.test(s)) return s;
  const dict = extra.length ? [...extra, ...DICT].sort((a, b) => b[0].length - a[0].length) : DICT;
  let out = '';
  let i = 0;
  while (i < s.length) {
    // すでに よみ付き
    RUBY_RUN.lastIndex = i;
    const m = RUBY_RUN.exec(s);
    if (m) {
      out += m[0];
      i += m[0].length;
      continue;
    }
    let hit = false;
    for (const [k, v] of dict) {
      if (s.startsWith(k, i)) {
        // 見出しの後ろに《》が続くなら（例 「数《すう》」の一部）合わせない
        if (s[i + k.length] === '《') continue;
        if (/[一-鿿]/.test(k[0]!) && /[一-鿿]/.test(s[i - 1] ?? '') && out.endsWith('》'))
          JOINED.set(`${s.slice(Math.max(0, i - 2), i)}+${k}`, s.slice(Math.max(0, i - 6), i + 6));
        out += v;
        i += k.length;
        hit = true;
        break;
      }
    }
    if (!hit) {
      if (/[一-鿿]/.test(s[i]!) && !MISSING.has(s[i]!))
        MISSING.set(s[i]!, s.slice(Math.max(0, i - 8), i + 8));
      out += s[i];
      i++;
    }
  }
  return out;
}

/** よみを付けない項目（ID・キー・SVG・根拠の文など） */
const SKIP = new Set([
  'id',
  'identity',
  'engine',
  'objective',
  'misconception',
  'reverseMisconception',
  'markup',
  'icon',
  'kind',
  'shape',
  'tone',
  'basis',
  'revised',
  'prereq',
  'stage',
  'subject',
  'domain',
  'priority',
  'status',
  'review',
]);

/** 問題データ・単元データの文に、まとめて《よみ》を付ける（関数はそのまま） */
export function rubyAll<T>(x: T, key = ''): T {
  if (typeof x === 'string') return (SKIP.has(key) ? x : R(x)) as T;
  if (Array.isArray(x)) return x.map((v) => rubyAll(v, key)) as T;
  if (x && typeof x === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(x)) out[k] = typeof v === 'function' ? v : rubyAll(v, k);
    return out as T;
  }
  return x;
}
