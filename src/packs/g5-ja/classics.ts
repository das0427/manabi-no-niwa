function matchItem(
  id: string,
  identity: string,
  objective: string,
  level: number,
  prompt: string,
  [, left, right, wrong, hints, e]: MatchDef,
): MatchItem {
  return {
    engine: 'match',
    id,
    objective,
    level,
    prompt,
    left: left.map((label) => ({ label })),
    right: right.map((label) => ({ label })),
    pairs: left.map((_, i) => [i, i] as [number, number]),
    wrongPairs: wrong,
    hints,
    explain: e,
    identity,
    alt: true,
  };
}

