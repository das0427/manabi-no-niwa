const ORD = ['1つめ', '2つめ', '3つめ'];

function poemItem(x: PoemQ): ReadingItem {
  const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
  return {
    engine: 'reading',
    id: `${x.p.id}:${x.k}`,
    objective: x.o,
    level: x.o === 'find' ? 0 : x.o === 'what' ? 1 : 2,
    aspect: x.o === 'effect' ? 'feeling' : 'detail',
    passage: x.p,
    prompt: x.q,
    options: opts(x.ok, x.wrong),
    hints: [
      `${paras.map((l) => ORD[l.p - 1]).join('と')}の連《れん》を読《よ》み返《かえ》そう。`,
      x.h2,
      x.h3,
    ],
    hintFocus: [paras, x.f, x.f],
    evidence: x.f,
    explain: x.e,
    identity: `fig:${x.p.id}:${x.k}`,
    alt: true,
  };
}

