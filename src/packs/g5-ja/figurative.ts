function classifyItem(x: (typeof CLASSIFY)[number]): ChoiceItem {
  // 擬人法の文では「比喩」を選択肢に入れない（擬人法も比喩の一つなので）
  const others: Kind[] = (['hiyu', 'giji', 'hanpuku', 'touchi'] as Kind[]).filter(
    (k) => k !== x.kind && !(x.kind === 'giji' && k === 'hiyu'),
  );
  return {
    engine: 'choice',
    id: `find-kind:${x.id}`,
    objective: 'find',
    level: 0,
    prompt: 'この文《ぶん》で使《つか》われている表現《ひょうげん》の工夫《くふう》はどれですか。',
    figure: { kind: 'text', text: x.s, size: 'm' },
    options: opts(
      KIND_LABEL[x.kind],
      others.map((k) => [KIND_LABEL[k], 'fig-kind-mix'] as const),
    ),
    layout: 'column',
    hints: [
      'たとえているか、人《ひと》のように書《か》いているか、くり返《かえ》しているか、順序《じゅんじょ》を入《い》れかえているかを見《み》よう。',
      '同《おな》じ言葉《ことば》が二回《にかい》以上《いじょう》出《で》てくるかな。文《ぶん》の終《お》わりが「〜を。」「〜へ。」のように、とちゅうで終《お》わっていないかな。',
      '人《ひと》でないものが、人《ひと》のような動《うご》きをしていないかも、たしかめよう。',
    ],
    explain: x.e,
    identity: `fig:find-kind:${x.id}`,
  };
}

