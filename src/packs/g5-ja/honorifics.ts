function kindMis(actual: Kind, chosen: Kind, oPrefix?: boolean): string {
  if (actual === 't' || chosen === 't') return 'hon-teinei';
  if (actual === 'k' && chosen === 's' && oPrefix) return 'hon-o-prefix';
  return 'hon-kind-who';
}

function kindItem([id, s, kind, e, oPrefix]: (typeof KIND)[number]): ChoiceItem {
  const wrong: Wrong[] = (['s', 'k', 't'] as Kind[])
    .filter((k) => k !== kind)
    .map((k) => [LABEL[k], kindMis(kind, k, oPrefix)]);
  return {
    engine: 'choice',
    id: `kind:${id}`,
    objective: 'kind',
    level: 0,
    prompt: '太字《ふとじ》の言葉《ことば》は、どの敬語《けいご》ですか。',
    figure: { kind: 'text', text: s, size: 'm' },
    options: opts(LABEL[kind], wrong),
    fixedOrder: true,
    hints: [
      '太字《ふとじ》の動作《どうさ》をしているのはだれかを、まず見《み》よう。',
      '相手《あいて》や話題《わだい》の人《ひと》の動作《どうさ》を高《たか》めるのが尊敬語《そんけいご》、自分《じぶん》や身内《みうち》の動作《どうさ》をへりくだるのが謙譲語《けんじょうご》、聞《き》き手《て》にていねいに言《い》うだけなのが丁寧語《ていねいご》だよ。',
      '「お」「ご」がついているかどうかだけでは決《き》まらないよ。動作《どうさ》をする人《ひと》とあわせて考《かんが》えよう。',
    ],
    explain: e,
    identity: `hon:kind:${id}`,
  };
}

