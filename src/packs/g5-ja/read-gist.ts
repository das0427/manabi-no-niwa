/**
 * g5.ja.read-gist 事実と意見・要旨（curriculum-matrix 3.8）。
 * 説明文: 事実の文と意見の文を見分ける → 筆者の考えの中心の文（だんらく）を選ぶ → 要旨を選ぶ。
 *
 * 本文はすべて本アプリのオリジナル。説明文6本（段階0・1）＋ 投書・学級新聞・提案の手紙3本（段階2、alt）。
 * 教科書の定番教材の題材は使わない。事実は確かなことだけを書き、言い切れないことは「〜といわれています」と書く
 * （その書き方自体を「伝え聞いたこと」として問う）。
 * 同一性キー: 本文ID × 設問（1.4）。別例の sort は カードの組ごとに1問。
 */
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { Item, SortItem, UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'fact' | 'center' | 'gist';

const ASPECT: Record<Obj, ReadingAspect> = {
  fact: 'detail',
  center: 'main-sentence',
  gist: 'gist',
};

interface Q {
  o: Obj;
  /** 設問の名前（同一性キー） */
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h2: string;
  h3: string;
  /** 根拠の場所（ヒント②③で囲み、正答で下線） */
  f: ReadingLoc[];
  e: string;
  h1?: string;
}

const CIRCLED = '①②③④⑤⑥⑦⑧⑨';

function build(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  return qs.map((x) => {
    const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
    const h1 =
      x.h1 ??
      `${paras.map((l) => CIRCLED[l.p - 1]).join('と')}のだんらくを読《よ》み返《かえ》そう。`;
    const level = alt ? 2 : x.o === 'fact' ? 0 : 1;
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level,
      aspect: ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: [paras, x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `gist:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

