/**
 * g5.ja.read-relations 物語: 人物の相互関係・心情を描写から（curriculum-matrix 3.8）。
 * 人物どうしの関係 → 行動・様子の表現から心情 → 関係の変化。
 *
 * 本文はすべて本アプリのオリジナル（再話なし）。物語6本＋別の文種（手紙・日記・詩）3本。
 * 同一性キー: 本文ID × 設問（同じ本文の同じ設問の言い換えは同じ: 1.4）。
 * 段階: 0 = 関係・心情（物語）、1 = 関係の変化（物語）、2 = 別の文種で確かめる（alt）。
 */
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'relation' | 'feeling' | 'change';

const ASPECT: Record<Obj, ReadingAspect> = {
  relation: 'character',
  feeling: 'feeling',
  change: 'character',
};

interface Q {
  o: Obj;
  /** 設問の名前（同一性キー） */
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h2: string;
  h3: string;
  /** 根拠の場所（ヒント②③で囲み、正答で下線） */
  f: ReadingLoc[];
  e: string;
  h1?: string;
}

const ORD = ['1つめ', '2つめ', '3つめ', '4つめ', '5つめ', '6つめ', '7つめ'];

function build(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  const unit = p.genre === 'poem' ? 'れん' : 'だんらく';
  return qs.map((x) => {
    const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
    const h1 =
      x.h1 ?? `${paras.map((l) => ORD[l.p - 1]).join('と')}の${unit}を読《よ》み返《かえ》そう。`;
    const level = alt ? 2 : x.o === 'change' ? 1 : 0;
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level,
      aspect: ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: [paras, x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `rel:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

