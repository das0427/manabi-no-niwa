function kakariItem(k: Kakari): ChoiceItem {
  return {
    engine: 'choice',
    id: `kakari:${k.id}`,
    objective: 'kakari',
    level: 0,
    prompt: k.q ?? KAKARI_Q,
    figure: { kind: 'text', text: k.s, size: 'm' },
    options: opts(k.ok, k.wrong),
    hints: [
      k.q
        ? '文《ぶん》の中《なか》の言葉《ことば》を一《ひと》つずつ組《く》み合《あ》わせて、意味《いみ》が通《とお》るかためそう。'
        : '太字《ふとじ》の言葉《ことば》と、ほかの言葉《ことば》を一《ひと》つずつつないで読《よ》み、意味《いみ》が通《とお》るかためそう。',
      k.h2,
      k.h3,
    ],
    explain: k.e,
    identity: `sr:kakari:${k.id}`,
  };
}

