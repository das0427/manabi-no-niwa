function miwakeItem([k, q, ok, wrong, h2, e, prompt]: (typeof MIWAKE)[number]): ChoiceItem {
  const a = q === 'A';
  return {
    engine: 'choice',
    id: `miwake:${k}`,
    objective: 'miwake',
    level: 0,
    prompt: prompt ?? (a ? PROMPT_A : PROMPT_B),
    options: opts(ok, wrong),
    layout: 'column',
    hints: [a ? HINT_A1 : HINT_B1, h2, a ? HINT_A3 : HINT_B3],
    explain: e,
    identity: `sw:miwake:${k}`,
  };
}

