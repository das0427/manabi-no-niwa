/**
 * g5.ja.text-figure 文章と図表を結び付ける（curriculum-matrix 3.8）。
 * 図表つきの報告文: 文の内容に合う図の部分を選ぶ → 図から文の根拠を見つける → 2つの資料を合わせて読む。
 *
 * 本文・図表はすべて本アプリのオリジナル。数はすべて架空の学校・町の例示データ（実在の調査ではない）で、
 * 題に「（れいのデータ）」と書く。
 * 報告文6本（段階0）＋ 2つの資料を合わせる本文3本（段階1）＋ 図表だけの問題（choice、段階2、alt）。
 * 同一性キー: 本文ID × 設問（1.4）。別例は問題ごと。
 */
import type { Figure } from '../../engines/figure/types';
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { ChoiceItem, Item, UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'fig' | 'evidence' | 'combine';

const ASPECT: Record<Obj, ReadingAspect> = {
  fig: 'detail',
  evidence: 'reason',
  combine: 'detail',
};

interface Q {
  o: Obj;
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h1?: string;
  h2: string;
  h3: string;
  f: ReadingLoc[];
  e: string;
}

const CIRCLED = '①②③④⑤⑥⑦⑧⑨';

function build(p: ReadingPassage, qs: Q[]): ReadingItem[] {
  return qs.map((x) => {
    const paras = [...new Set(x.f.map((l) => l.p))].map((n) => ({ p: n }));
    const h1 =
      x.h1 ??
      `${paras.map((l) => CIRCLED[l.p - 1]).join('と')}のだんらくを読《よ》んでから、図《ず》や表《ひょう》を見《み》よう。`;
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level: x.o === 'combine' ? 1 : 0,
      aspect: ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: [paras, x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `tf:${p.id}:${x.k}`,
    };
  });
}

const label = (t: string): Figure => ({ kind: 'text', text: t, size: 'm' });

