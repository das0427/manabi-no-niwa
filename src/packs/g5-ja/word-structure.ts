const keyOf = (w: string) => w.replace(/《[^》]*》/g, '');

function jukugoItem([q, ok, wrongs]: (typeof JUKUGO)[number]): ChoiceItem {
  const [t, gq] = W[q]!;
  const [, gok] = W[ok]!;
  return {
    engine: 'choice',
    id: `jukugo:${keyOf(q)}`,
    objective: 'jukugo',
    level: 0,
    prompt:
      '上《うえ》の熟語《じゅくご》と同《おな》じ組《く》み立《た》ての熟語《じゅくご》はどれですか。',
    figure: { kind: 'text', text: q, size: 'xl' },
    options: opts(
      ok,
      wrongs.map((w) => [w, jtMis(t, W[w]![0])] as const),
    ),
    hints: [
      '上《うえ》の熟語《じゅくご》を、一字《いちじ》ずつの意味《いみ》に分《わ》けて考《かんが》えよう。',
      `上《うえ》の熟語《じゅくご》は「${gq}」と言《い》いかえられるね。`,
      'えらぶ熟語《じゅくご》も一《ひと》つずつ言《い》いかえて、同《おな》じ形《かたち》の言《い》いかえになるものをさがそう。',
    ],
    explain: `「${q}」は「${gq}」で、${JT_DESC[t]}です。「${ok}」も「${gok}」なので、同《おな》じ組《く》み立《た》てです。`,
    identity: `ws:jukugo:${keyOf(q)}`,
  };
}

