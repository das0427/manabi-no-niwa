/** 書き方: kanji 漢字 / hira ひらがな / kata カタカナ */
type Script = 'kanji' | 'hira' | 'kata';

function goshuMis(actual: GT, chosen: GT, script: Script): string {
  if (actual === 'w' && chosen === 'k' && script === 'kanji') return 'ws-kanji-kango';
  if (actual === 'k' && chosen === 'w' && script === 'hira') return 'ws-hiragana-wago';
  if (actual === 'w' && chosen === 'g' && script === 'kata') return 'ws-katakana-gairaigo';
  if (actual === 'k' && chosen === 'w') return 'ws-on-kun';
  return 'ws-goshu-origin';
}

