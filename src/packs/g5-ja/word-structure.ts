function jtMis(a: JT, b: JT): string {
  if (a === 'e' || b === 'e') return 'ws-subject';
  const s = new Set([a, b]);
  if (s.has('a') && s.has('b')) return 'ws-similar-opposite';
  if (s.has('c') && s.has('d')) return 'ws-modify-object';
  return 'ws-meaning';
}

