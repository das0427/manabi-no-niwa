const PART_LABEL = {
  はじめ: 'はじめ（話題《わだい》）',
  中: '中《なか》（調《しら》べた事実《じじつ》）',
  終わり: '終《お》わり（事実《じじつ》をもとにした考《かんが》え）',
} as const;

function kouseiAlt(a: (typeof KOUSEI_ALT)[number]): ChoiceItem {
  const t = THEMES.find((x) => x.id === a.theme)!;
  const byPart = { はじめ: t.intro, 中: t.facts[0], 終わり: t.opinions[1] } as const;
  const parts = ['はじめ', '中', '終わり'] as const;
  return {
    engine: 'choice',
    id: `kousei-alt:${a.id}`,
    objective: 'kousei',
    level: 1,
    alt: true,
    prompt: `「${t.title}」の意見文《いけんぶん》の構成表《こうせいひょう》です。「${PART_LABEL[a.part]}」に入《い》れる文《ぶん》としてよいものはどれですか。`,
    options: opts(
      byPart[a.part],
      parts.filter((p) => p !== a.part).map((p) => [byPart[p], 'fo-order'] as const),
    ),
    layout: 'column',
    hints: [
      `「${PART_LABEL[a.part]}」には、どんなことを書《か》くのかを思《おも》い出《だ》そう。`,
      'それぞれの文《ぶん》が、話題《わだい》・事実《じじつ》・考《かんが》えのどれにあたるか考《かんが》えよう。',
      '数《かず》や見《み》たことは事実《じじつ》、「〜と考《かんが》えます」は考《かんが》え、「〜について調《しら》べました」は話題《わだい》だよ。',
    ],
    explain: `「${PART_LABEL[a.part]}」に入《い》るのは「${byPart[a.part]}」です。構成表《こうせいひょう》は ${KOUSEI} の順《じゅん》です。`,
    identity: `fo:kousei-alt:${a.id}`,
  };
}

