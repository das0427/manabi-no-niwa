// ---- 1. 事実と意見を分ける ----
function bunruiItem(t: Theme): SortItem {
  return {
    engine: 'sort',
    id: `bunrui:${t.id}`,
    objective: 'bunrui',
    level: 0,
    prompt: `「${t.title}」について書《か》いた文《ぶん》を、事実《じじつ》と意見《いけん》に分《わ》けよう。`,
    boxes: [{ label: FACT }, { label: OPINION }],
    cards: [
      { label: t.facts[0], box: 0, wrongBoxes: [{ box: 1, misconception: 'fo-fact-as-opinion' }] },
      { label: t.facts[1], box: 0, wrongBoxes: [{ box: 1, misconception: 'fo-heard-as-opinion' }] },
      { label: t.facts[2], box: 0, wrongBoxes: [{ box: 1, misconception: 'fo-fact-as-opinion' }] },
      ...t.opinions.map((label) => ({
        label,
        box: 1,
        wrongBoxes: [{ box: 0, misconception: 'fo-opinion-as-fact' }],
      })),
    ],
    hints: HINTS_SORT,
    explain: `事実《じじつ》は、調《しら》べて確《たし》かめた三《みっ》つの文《ぶん》です。人《ひと》が答《こた》えたこと・話《はな》したことも、「そう答《こた》えた・そう話《はな》した」という事実《じじつ》です。意見《いけん》は「${t.opinions[0]}」と「${t.opinions[1]}」です。`,
    identity: `fo:bunrui:${t.id}`,
  };
}

