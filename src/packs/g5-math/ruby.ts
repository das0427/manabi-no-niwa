type Dict = [string, string][];

function parseWords(words: string): Dict {
  return words
    .split(/\s+/)
    .filter((w) => w)
    .map((w) => [w.replace(/《[^》]*》/g, ''), w] as [string, string]);
}

const BASE: Dict = parseWords(WORDS);

/** 辞書に無かった漢字（検査用） */
export const MISSING = new Map<string, string>();

const RUBY_RUN = /[一-鿿㐀-䶿々〆ヶ]+《[^》]*》/y;

function rubyWith(dict: Dict, s: string): string {
  if (!/[一-鿿]/.test(s)) return s;
  let out = '';
  let i = 0;
  while (i < s.length) {
    RUBY_RUN.lastIndex = i;
    const m = RUBY_RUN.exec(s);
    if (m) {
      out += m[0];
      i += m[0].length;
      continue;
    }
    let hit = false;
    for (const [k, v] of dict) {
      if (s.startsWith(k, i)) {
        if (s[i + k.length] === '《') continue;
        out += v;
        i += k.length;
        hit = true;
        break;
      }
    }
    if (!hit) {
      if (/[一-鿿]/.test(s[i]!) && !MISSING.has(s[i]!)) MISSING.set(s[i]!, s.slice(Math.max(0, i - 8), i + 8));
      out += s[i];
      i++;
    }
  }
  return out;
}

/** よみを付けない項目（ID・キー・SVG・根拠の文など） */
const SKIP = new Set([
  'id',
  'identity',
  'engine',
  'objective',
  'misconception',
  'reverseMisconception',
  'markup',
  'icon',
  'kind',
  'shape',
  'tone',
  'basis',
  'revised',
  'prereq',
  'stage',
  'subject',
  'domain',
  'priority',
  'status',
  'review',
  'value',
]);

export interface Ruby {
  R: (s: string) => string;
  rubyAll: <T>(x: T) => T;
}

/** 追加の語（'語《ご》 語《ご》 …'）を足した よみ付けの関数 */
export function makeRuby(extra = ''): Ruby {
  const dict = [...parseWords(extra), ...BASE].sort((a, b) => b[0].length - a[0].length);
  const cache = new Map<string, string>();
  const R = (s: string) => {
    let v = cache.get(s);
    if (v === undefined) {
      v = rubyWith(dict, s);
      if (cache.size < 50000) cache.set(s, v);
    }
    return v;
  };
  const walk = (x: unknown, key: string): unknown => {
    if (typeof x === 'string') return SKIP.has(key) ? x : R(x);
    if (Array.isArray(x)) return x.map((v) => walk(v, key));
    if (x && typeof x === 'object') {
      const out: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(x)) out[k] = typeof v === 'function' ? v : walk(v, k);
      return out;
    }
    return x;
  };
  return { R, rubyAll: <T,>(x: T) => walk(x, '') as T };
}
