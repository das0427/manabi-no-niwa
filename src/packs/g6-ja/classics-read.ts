// ---- 3. 解説文を読む ----

interface Q {
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h2: string;
  h3: string;
  f: ReadingLoc[];
  e: string;
  h1?: string;
}

const CIRCLED = '①②③④⑤⑥⑦⑧⑨';

function readItems(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  return qs.map((x) => {
    const nums = [...new Set(x.f.map((l) => l.p))];
    const h1 =
      x.h1 ??
      (p.numbered
        ? `${nums.map((n) => CIRCLED[n - 1]).join('と')}の段落《だんらく》を読《よ》み返《かえ》そう。`
        : '本文《ほんぶん》と表《ひょう》を読《よ》み返《かえ》そう。');
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: 'kaisetsu',
      level: 2,
      aspect: 'detail',
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: [nums.map((n) => ({ p: n })), x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `cls:yomu:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

