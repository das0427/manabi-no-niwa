function pairsItem(p: Pairs): MatchItem {
  const n = p.pairs.length;
  return {
    engine: 'match',
    id: `musubu:${p.id}`,
    objective: 'cause',
    level: 0,
    prompt: `上《うえ》の${GEN}と、そのために起《お》きた下《した》の${KEK}を、線《せん》で結《むす》ぼう。`,
    left: p.pairs.map(([c]) => ({ label: c })),
    right: [...p.pairs.map(([, r]) => ({ label: r })), { label: p.extra }],
    pairs: p.pairs.map((_, i) => [i, i] as [number, number]),
    wrongPairs: [{ pair: [p.extraFrom, n], misconception: 'ir-unrelated' }],
    hints: [
      `${GEN}は「そうなったわけ」、${KEK}は「そのために起《お》きたこと」だよ。`,
      '上《うえ》の一《ひと》つを読《よ》んで、「〜したので、どうなる？」と考《かんが》えてみよう。',
      '下《した》には、どの原因《げんいん》とも結《むす》び付《つ》かないものが一《ひと》つまざっているよ。「〜したので、〜した」とつなげて、おかしくないかたしかめよう。',
    ],
    explain: p.e,
    identity: `ir:musubu:${p.id}`,
  };
}

