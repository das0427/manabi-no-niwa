function causeAltItem(x: (typeof CAUSE_ALT)[number]): ChoiceItem {
  return {
    engine: 'choice',
    id: `musubu-alt:${x.id}`,
    objective: 'cause',
    level: 0,
    prompt: x.q,
    figure: { kind: 'text', text: x.s, size: 'm' },
    options: opts(x.ok, x.wrong),
    layout: 'column',
    hints: [
      '文章《ぶんしょう》に書《か》かれたできごとを、起《お》きた順《じゅん》にたしかめよう。',
      '「そのため」「だから」「すると」のような言葉《ことば》の前《まえ》と後《あと》に注目《ちゅうもく》しよう。',
      '「〇〇したので、△△になった」とつなげて、いちばん自然《しぜん》につながるものをさがそう。',
    ],
    explain: x.e,
    identity: `ir:musubu-alt:${x.id}`,
    alt: true,
  };
}

