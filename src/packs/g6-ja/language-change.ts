type Obj = 'dialect' | 'change' | 'origin' | 'kana' | 'kanji';
const LEVEL: Record<Obj, number> = { dialect: 0, change: 1, origin: 2, kana: 3, kanji: 3 };

// ---- match ----
interface M {
  id: string;
  obj: Obj;
  prompt: string;
  hints: [string, string, string];
  left: string[];
  /** 正しい相手（left と同じ順）→ そのあとにまぎらわしいもの */
  right: string[];
  wrong?: [number, number][];
  mis?: string;
  e: string;
}

function matchItem(m: M): MatchItem {
  return {
    engine: 'match',
    id: m.id,
    objective: m.obj,
    level: LEVEL[m.obj],
    prompt: m.prompt,
    left: m.left.map((label) => ({ label })),
    right: m.right.map((label) => ({ label })),
    pairs: m.left.map((_, i) => [i, i] as [number, number]),
    ...(m.wrong && m.mis
      ? { wrongPairs: m.wrong.map((pair) => ({ pair, misconception: m.mis as string })) }
      : {}),
    hints: m.hints,
    explain: m.e,
    identity: `lc:${m.obj}:match:${m.id.split(':')[1]}`,
  };
}

