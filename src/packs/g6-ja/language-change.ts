const CIRCLED = '①②③④⑤⑥⑦⑧⑨';

interface Q {
  k: string;
  obj: Obj;
  aspect: 'detail' | 'gist' | 'reason';
  q: string;
  c: string;
  w: Wrong[];
  f: ReadingLoc;
  h2: string;
  h3: string;
  e: string;
}

function readItems(p: ReadingPassage, qs: Q[]): ReadingItem[] {
  return qs.map((x) => ({
    engine: 'reading' as const,
    id: `${p.id}:${x.k}`,
    objective: x.obj,
    level: LEVEL[x.obj],
    aspect: x.aspect,
    passage: p,
    prompt: x.q,
    options: opts(x.c, x.w),
    hints: [`${CIRCLED[x.f.p - 1]}の段落《だんらく》を読《よ》み返《かえ》そう。`, x.h2, x.h3],
    hintFocus: [[{ p: x.f.p }], [x.f], [x.f]],
    evidence: [x.f],
    explain: x.e,
    identity: `lc:${x.obj}:read:${p.id}:${x.k}`,
    alt: true,
  }));
}

