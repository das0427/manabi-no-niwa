function choiceItem(c: C): ChoiceItem {
  return {
    engine: 'choice',
    id: c.id,
    objective: c.obj,
    level: LEVEL[c.obj],
    prompt: c.p,
    ...(c.fig ? { figure: c.fig } : {}),
    options: opts(c.ok, c.w),
    ...(c.col ? { layout: 'column' as const } : {}),
    hints: c.h,
    explain: c.e,
    identity: `lc:${c.obj}:${c.alt ? 'alt' : 'choice'}:${c.id}`,
    ...(c.alt ? { alt: true } : {}),
  };
}

