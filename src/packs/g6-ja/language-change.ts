/**
 * g6.ja.language-change 方言と共通語、言葉の変化と由来（curriculum-matrix 3.9。P2）。
 * 方言と共通語 → 言葉の移り変わり（世代・古語・仮名づかい）→ 言葉の生まれ（語源・外来語）→
 * 文字の由来（ひらがな・カタカナ・漢字の成り立ち）。match で対応させ、choice で確かめ、
 * 解説文（reading）を読む。別例は会話・文の中で確かめる choice と reading。
 * 設計書: docs/expansion/p2-design/g6-ja.md
 *
 * 方言は意味がはっきりした有名なものだけを使い、どの地方の言葉かは答えさせない（解説は「〜などで」とぼかす）。
 * 語源は辞書で通説とされるものだけ（確かでないものは「といわれる」）。古文は著作権の切れた原典から短く。
 * 例・本文・設問はすべて本アプリのオリジナル。
 *
 * 同一性キー: `lc:<到達項目>:<種類>:<id>`（match は組の集合ごと、choice・reading は設問ごと）。
 */
import type { ChoiceItem, Item, MatchItem, ReadingItem, UnitSpec } from '../../curriculum/types';
