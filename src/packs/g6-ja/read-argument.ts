/**
 * g6.ja.read-argument 筆者の主張と根拠、論の進め方（curriculum-matrix 3.9）。
 * 説明文・意見文: 主張の文を見つける → 主張を支える根拠・事例を読む → 論の進め方（頭括・尾括・双括、
 * 比べる・反論に答える など）をとらえる。
 *
 * 本文はすべて本アプリのオリジナル。意見文6本＋別の文種（投書・スピーチ原稿・討論の記録）3本。
 * 事例は書き手の身の回りのできごとにとどめ、数値は使わない。登場する名前は架空。
 * 同一性キー: 本文ID × 設問（同じ本文の同じ設問の言い換えは同じ: 1.4）。
 * 段階: 0 = 主張、1 = 根拠・事例、2 = 論の進め方。別の文種の設問は alt（各段階に1問ずつ）。
 */
import type {
  ReadingAspect,
  ReadingItem,
  ReadingLoc,
  ReadingPassage,
} from '../../engines/reading/reading';
import type { UnitSpec } from '../../curriculum/types';
import { REVISED } from './util';

type Obj = 'claim' | 'ground' | 'structure';

const ASPECT: Record<Obj, ReadingAspect> = {
  claim: 'main-sentence',
  ground: 'reason',
  structure: 'order',
};
const LEVEL: Record<Obj, number> = { claim: 0, ground: 1, structure: 2 };

interface Q {
  o: Obj;
  /** 設問の名前（同一性キー） */
  k: string;
  q: string;
  c: string;
  w: [string, string][];
  h2: string;
  h3: string;
  /** 根拠の場所（ヒント②③で囲み、正答で下線） */
  f: ReadingLoc[];
  e: string;
  h1?: string;
}

const CIRCLED = '①②③④⑤⑥⑦⑧⑨';
const ORD = ['1つめ', '2つめ', '3つめ', '4つめ', '5つめ', '6つめ'];
const H1_STRUCTURE =
  '段落《だんらく》ごとに、何《なに》が書《か》いてあるか（主張《しゅちょう》・例《れい》・理由《りゆう》など）を短《みじか》くまとめてみよう。';

function build(p: ReadingPassage, qs: Q[], alt: boolean): ReadingItem[] {
  return qs.map((x) => {
    const nums = [...new Set(x.f.map((l) => l.p))];
    const paras = nums.map((n) => ({ p: n }));
    const where = p.numbered
      ? `${nums.map((n) => CIRCLED[n - 1]).join('と')}の段落《だんらく》`
      : `${nums.map((n) => ORD[n - 1]).join('と')}のまとまり`;
    const h1 =
      x.h1 ?? (x.o === 'structure' ? H1_STRUCTURE : `${where}を読《よ》み返《かえ》そう。`);
    return {
      engine: 'reading',
      id: `${p.id}:${x.k}`,
      objective: x.o,
      level: LEVEL[x.o],
      aspect: ASPECT[x.o],
      passage: p,
      prompt: x.q,
      options: [
        { label: x.c, correct: true },
        ...x.w.map(([label, misconception]) => ({ label, misconception })),
      ],
      hints: [h1, x.h2, x.h3],
      hintFocus: [x.o === 'structure' ? null : paras, x.f, x.f],
      evidence: x.f,
      explain: x.e,
      identity: `arg:${p.id}:${x.k}`,
      ...(alt ? { alt: true } : {}),
    };
  });
}

