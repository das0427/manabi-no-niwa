const KOUSEI =
  '主張《しゅちょう》 → 根拠《こんきょ》 → 予想《よそう》される反論《はんろん》とその答《こた》え → まとめ';

// ---- 1. 構成表の順 ----
function kouseiItem(t: Theme): OrderItem {
  return {
    engine: 'order',
    id: `kousei:${t.id}`,
    objective: 'kousei',
    level: 0,
    layout: 'column',
    prompt: `「${t.title}」についての意見文《いけんぶん》です。だんらくを、構成表《こうせいひょう》の順《じゅん》（${KOUSEI}）にならべよう。`,
    cards: t.cards.map((label) => ({ label })),
    ends: ['はじめ', '終《お》わり'],
    reverseMisconception: 'wo-order',
    wrongOrders: [
      { order: [0, 2, 1, 3], misconception: 'wo-order' },
      { order: [1, 0, 2, 3], misconception: 'wo-order' },
      { order: [0, 1, 3, 2], misconception: 'wo-order' },
    ],
    hints: [
      'まず、書《か》き手《て》がいちばん言《い》いたいこと（主張《しゅちょう》）の文《ぶん》を見《み》つけよう。',
      '主張《しゅちょう》を支《ささ》える文《ぶん》が根拠《こんきょ》。「〜もあるが」と心配《しんぱい》に答《こた》える文《ぶん》が反論《はんろん》とその答《こた》えだよ。',
      '「〜ため、〜を提案《ていあん》します」のように、主張《しゅちょう》をもう一度《いちど》まとめる文《ぶん》は最後《さいご》だよ。',
    ],
    explain:
      '主張《しゅちょう》、根拠《こんきょ》、反論《はんろん》とその答《こた》え、まとめの順《じゅん》です。反論《はんろん》に答《こた》えてからまとめると、読《よ》む人《ひと》が納得《なっとく》しやすくなります。',
    identity: `wo:kousei:${t.id}`,
  };
}

