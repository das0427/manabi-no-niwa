const KOUSEI =
  '主張《しゅちょう》 → 根拠《こんきょ》 → 予想《よそう》される反論《はんろん》とその答《こた》え → まとめ';

// ---- 1. 構成表の順 ----
function kouseiItem(t: Theme): OrderItem {
  return {
    engine: 'order',
    id: `kousei:${t.id}`,
    objective: 'kousei',
    level: 0,
    layout: 'column',
    prompt: `「${t.title}」についての意見文《いけんぶん》です。だんらくを、構成表《こうせいひょう》の順《じゅん》（${KOUSEI}）にならべよう。`,
    cards: [
      { label: t.claim },
      { label: t.grounds.join('') },
      { label: t.rebuttal + t.answer },
      { label: t.conclusion },
    ],
    ends: ['はじめ', '終《お》わり'],
    reverseMisconception: 'wo-order',
    wrongOrders: [
      { order: [0, 2, 1, 3], misconception: 'wo-order' },
      { order: [1, 0, 2, 3], misconception: 'wo-order' },
      { order: [0, 1, 3, 2], misconception: 'wo-order' },
    ],
    hints: [
      'まず、書《か》き手《て》がいちばん言《い》いたいこと（主張《しゅちょう》）の文《ぶん》を見《み》つけよう。',
      '「〜と答《こた》えた人《ひと》が」「〜だからです」のように主張《しゅちょう》を支《ささ》える文《ぶん》が根拠《こんきょ》、「〜という意見《いけん》もあるでしょう。しかし」が反論《はんろん》とその答《こた》えだよ。',
      '「〜ために、〜を提案《ていあん》します」のように、主張《しゅちょう》をもう一度《いちど》まとめるだんらくは最後《さいご》だよ。',
    ],
    explain: `主張《しゅちょう》「${t.claim}」→ 根拠《こんきょ》 → 予想《よそう》される反論《はんろん》とその答《こた》え → まとめ「${t.conclusion}」の順《じゅん》です。反論《はんろん》に答《こた》えてから主張《しゅちょう》をまとめると、読《よ》む人《ひと》が納得《なっとく》しやすくなります。`,
    identity: `wo:kousei:${t.id}`,
  };
}

/** 別例: 構成表の箱に分ける（sort） */
function kouseiSort(t: Theme): SortItem {
  return {
    engine: 'sort',
    id: `kousei-sort:${t.id}`,
    objective: 'kousei',
    level: 0,
    alt: true,
    prompt: `「${t.title}」の意見文《いけんぶん》の文《ぶん》を、構成表《こうせいひょう》の四《よっ》つの箱《はこ》に分《わ》けよう。`,
    boxes: [
      { label: '主張《しゅちょう》' },
      { label: '根拠《こんきょ》' },
      { label: '予想《よそう》される反論《はんろん》' },
      { label: '反論《はんろん》への答《こた》え' },
    ],
    cards: [
      { label: t.claim, box: 0, wrongBoxes: [{ box: 1, misconception: 'wo-circular' }] },
      ...t.grounds.map((label) => ({
        label,
        box: 1,
        wrongBoxes: [{ box: 3, misconception: 'wo-rebuttal-ground' }],
      })),
      { label: t.rebuttal, box: 2, wrongBoxes: [{ box: 1, misconception: 'wo-rebuttal-ground' }] },
      { label: t.answer, box: 3, wrongBoxes: [{ box: 1, misconception: 'wo-rebuttal-ground' }] },
    ],
    hints: [
      'いちばん言《い》いたいこと（主張《しゅちょう》）は一《ひと》つだけだよ。',
      '「〜という意見《いけん》もあるでしょう」は、自分《じぶん》とはちがう立場《たちば》の人《ひと》が言《い》いそうなこと（反論《はんろん》）だよ。',
      '「しかし」「けれども」「そこで」で始《はじ》まり、反論《はんろん》の心配《しんぱい》をなくす文《ぶん》が、反論《はんろん》への答《こた》えだよ。',
    ],
    explain: `主張《しゅちょう》は「${t.claim}」、予想《よそう》される反論《はんろん》は「${t.rebuttal}」、その答《こた》えは「${t.answer}」です。のこりの二《ふた》つが根拠《こんきょ》です。`,
    identity: `wo:kousei-sort:${t.id}`,
  };
}

