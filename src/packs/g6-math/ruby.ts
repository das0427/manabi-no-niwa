/** 見出し → よみ付きの語（長い見出しが先） */
const DICT: [string, string][] = WORDS.split(/\s+/)
  .filter((w) => w)
  .map((w) => [w.replace(/《[^》]*》/g, ''), w] as [string, string])
  .sort((a, b) => b[0].length - a[0].length);

const RUBY_RUN = /[一-鿿㐀-䶿々〆ヶ]+《[^》]*》/y;

/** 文に《よみ》を付ける */
export function R(s: string): string {
  if (!/[一-鿿]/.test(s)) return s;
  let out = '';
  let i = 0;
  while (i < s.length) {
    RUBY_RUN.lastIndex = i;
    const m = RUBY_RUN.exec(s);
    if (m) {
      out += m[0];
      i += m[0].length;
      continue;
    }
    let hit = false;
    for (const [k, v] of DICT) {
      if (s.startsWith(k, i)) {
        if (s[i + k.length] === '《') continue;
        out += v;
        i += k.length;
        hit = true;
        break;
      }
    }
    if (!hit) {
      out += s[i];
      i++;
    }
  }
  return out;
}

/** よみを付けない項目（ID・キー・SVG・根拠の文など） */
const SKIP = new Set([
  'id',
  'identity',
  'engine',
  'objective',
  'misconception',
  'reverseMisconception',
  'markup',
  'icon',
  'kind',
  'shape',
  'tone',
  'basis',
  'revised',
  'prereq',
  'stage',
  'subject',
  'domain',
  'priority',
  'status',
  'review',
]);

/** 問題データ・単元データの文に、まとめて《よみ》を付ける（関数はそのまま） */
export function rubyAll<T>(x: T, key = ''): T {
  if (typeof x === 'string') return (SKIP.has(key) ? x : R(x)) as T;
  if (Array.isArray(x)) return x.map((v) => rubyAll(v, key)) as T;
  if (x && typeof x === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(x)) out[k] = typeof v === 'function' ? v : rubyAll(v, k);
    return out as T;
  }
  return x;
}
