interface Q {
  id: string;
  level: number;
  prompt: string;
  figure?: Figure;
  right: string;
  rightFig?: string;
  wrongs: [string, string][];
  wrongFigs?: string[];
  hints: [string, string, string];
  explain: string;
}
/** 文の選択肢は layout: column。絵の選択肢（rightFig）と作業領域の図つき（figure）は layout を渡さない */
const toItem = (q: Q, obj: string, alt: boolean): ChoiceItem =>
  choiceItem({
    id: q.id,
    obj,
    level: q.level,
    prompt: q.prompt,
    ...(q.figure ? { figure: q.figure } : {}),
    right: q.right,
    ...(q.rightFig ? { rightFigure: illust(q.rightFig) } : {}),
    wrongs: q.wrongs,
    ...(q.wrongFigs ? { wrongFigures: q.wrongFigs.map((f) => illust(f)) } : {}),
    ...(q.rightFig || q.figure ? {} : { layout: 'column' as const }),
    hints: q.hints,
    explain: q.explain,
    ...(alt ? { alt: true } : {}),
  });

