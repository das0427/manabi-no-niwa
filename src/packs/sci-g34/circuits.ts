/** 回路の図（かん電池・豆電球・どう線）。gap: 右の どう線が とちゅうで 切れて いる */
function circuitSvg(gap: boolean) {
  const right = gap
    ? '<polyline points="136,152 170,152 170,112"/><polyline points="170,88 170,40 116,40"/>'
    : '<polyline points="136,152 170,152 170,40 116,40"/>';
  return svg(
    `<svg viewBox="0 0 200 180" xmlns="http://www.w3.org/2000/svg">` +
      `<g stroke="var(--ink)" stroke-width="3.5" fill="none" stroke-linejoin="round" stroke-linecap="round">` +
      `<polyline points="70,152 30,152 30,40 84,40"/>${right}</g>` +
      `<rect x="70" y="140" width="60" height="24" rx="4" fill="var(--sun)" stroke="var(--ink)" stroke-width="3.5"/>` +
      `<rect x="130" y="146" width="6" height="12" fill="var(--ink-soft)"/>` +
      `<circle cx="100" cy="40" r="16" fill="var(--paper)" stroke="var(--ink)" stroke-width="3.5"/>` +
      `</svg>`,
    gap
      ? 'かん電池《でんち》と 豆電球《まめでんきゅう》の 回路《かいろ》。右《みぎ》の どう線《せん》が とちゅうで 切《き》れて いる'
      : 'かん電池《でんち》と 豆電球《まめでんきゅう》の 回路《かいろ》。どう線《せん》が わのように つながって いる',
  );
}

