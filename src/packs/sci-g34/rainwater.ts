/** 選択肢を あいうの じゅんに ならべる（記号だけの 選択肢は エンジンが 並べ替えないため） */
function symbolOrder(item: ChoiceItem): ChoiceItem {
  const key = (o: ChoiceItem['options'][number]) => (typeof o.label === 'string' ? o.label : '');
  return { ...item, options: [...item.options].sort((a, b) => key(a).localeCompare(key(b), 'ja')) };
}

