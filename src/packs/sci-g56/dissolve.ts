function rowsOf(things: string[], waters: string[], temps: string[]) {
  return things.flatMap((th) =>
    waters.flatMap((w) =>
      temps.map((t) => ({
        when: { thing: th, water: w, temp: t },
        result: `約《やく》${AMOUNT[`${th}-${w}-${t}`]}g`,
      })),
    ),
  );
}
