function match(s: {
  id: string;
  obj: string;
  level: number;
  prompt: RichText;
  left: RichText[];
  right: RichText[];
  pairs: [number, number][];
  wrongPairs?: { pair: [number, number]; misconception: string }[];
  hints: Hints;
  explain: RichText;
  alt?: boolean;
}): MatchItem {
  return {
    engine: 'match',
    id: s.id,
    objective: s.obj,
    level: s.level,
    prompt: s.prompt,
    hints: s.hints,
    explain: s.explain,
    identity: s.id,
    ...(s.alt ? { alt: true } : {}),
    left: s.left.map((label) => ({ label })),
    right: s.right.map((label) => ({ label })),
    pairs: s.pairs,
    ...(s.wrongPairs ? { wrongPairs: s.wrongPairs } : {}),
  };
}

