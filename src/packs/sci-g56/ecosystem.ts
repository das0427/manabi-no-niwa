/**
 * g6.sci.ecosystem 生物と かん境（設計書 docs/expansion/p2-design/sci-g6.md 4章）。
 *
 * 身近な池や林で生物を観察するのが本体／食べる・食べられるの例は一般に知られた組（草→バッタ→カエル→ヘビ、ミカヅキモ→ミジンコ→メダカ、イネ→バッタ→カマキリ、草→ウサギ→キツネ、木の葉→イモムシ→小鳥→タカ）。生物の名前はカタカナの一般名／植物に袋をかぶせて息をふきこむ実験の気体の割合（酸素 約17%→約19%、二酸化炭素 約4%→約2%）は「れい」。暗い所では植物も呼吸だけをするので酸素が少し減る（例示の固定表）／人と環境は、責めない・おどさない書き方で、くらしの工夫（水をきれいにして返す、森林、電気をむだなく使う）にとどめる。「食物連鎖」の語は使わない（鎖が小学校の字でないため。「食べる・食べられる 関係」と書く）。
 *
 * 到達項目:
 *   food … 食べる・食べられるの関係は植物から始まる。順にならべる。1つの生物が減ると ほかにひびく
 *   air … 植物は日光が当たると二酸化炭素を取り入れ酸素を出す。動物も植物も呼吸で酸素を使う
 *   water … 生物の体は水を多くふくむ。水は かん境と生物の間をめぐる。人は かん境を守る工夫をしている
 * 場面（7）: 陸の食べる・食べられる／池の食べる・食べられる／人の食べ物のもと／植物に息をふきこむ実験（日光・暗い所）／動物と植物の呼吸／水のめぐり／人のくらしとかん境
 * 同一性キー: 問題の id。
 */
