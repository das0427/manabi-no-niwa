const LEVER_MIS = { weightOnly: 'lev-weight-only', distanceOnly: 'lev-distance-only' };

function num(s: {
  id: string;
  obj: string;
  level: number;
  prompt: string;
  answer: number;
  unit: string;
  wrong: [number, string][];
  hints: [string, string, string];
  explain: string;
  alt?: boolean;
  figure?: NumberItem['figure'];
}): NumberItem {
  return {
    engine: 'number',
    id: s.id,
    objective: s.obj,
    level: s.level,
    prompt: s.prompt,
    ...(s.figure ? { figure: s.figure } : {}),
    fields: [{ unit: s.unit, answer: { kind: 'int', value: s.answer } }],
    wrongAnswers: s.wrong.map(([v, m]) => ({ value: String(v), misconception: m })),
    hints: s.hints,
    explain: s.explain,
    identity: s.id,
    ...(s.alt ? { alt: true } : {}),
  };
}

