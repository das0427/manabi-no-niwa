/**
 * g6.sci.lever てこの きまり（curriculum-matrix 3.9、理6A てこの規則性）。
 *
 * つり合いは experiment の lever（左右の「おもりの 重さ × 支点からの きょり（目もりの 番号）」を くらべる
 * 「この アプリの せってい」）。実験用てこで ほんものの おもりを つるして たしかめるのが本体。
 *
 * 到達項目:
 *   points  … 支点・力点・作用点と 手ごたえ（力点を 支点から 遠ざける・作用点を 支点に 近づけると 小さい 力で すむ）
 *   balance … てこが つり合う きまり（重さ × きょり が 左右で 等しい）
 *   tools   … てこを 利用した 道具（3つの 点の ならび方）
 * 場面（6）: 棒で 重い 物を 持ち上げる／実験用てこで つり合わせる／おもりの 位置を かえる／何《なん》g で つり合うか 計算する／
 *            はさみ・くぎぬき／せんぬき・ピンセット
 * 同一性キー: 問題の id。
 */
