/**
 * 位置関係の 模式図。太陽は 右の はし。地球は 中央。月は 地球の まわりの 角度 deg（0 = 太陽の 側、
 * 90 = 上、180 = 太陽と 反対）。月は 右（太陽の 側）の 半分が 光る。
 */
function orbit(deg: number, label: string): Figure {
  const cx = 150;
  const cy = 100;
  const R = 70;
  const rad = (deg * Math.PI) / 180;
  const mx = Math.round(cx + R * Math.cos(rad));
  const my = Math.round(cy - R * Math.sin(rad));
  const r = 14;
  const sunRays = [0, 1, 2, 3, 4, 5, 6, 7]
    .map((i) => {
      const a = (i * Math.PI) / 4;
      return `<line x1="${Math.round(292 + 26 * Math.cos(a))}" y1="${Math.round(100 + 26 * Math.sin(a))}" x2="${Math.round(292 + 34 * Math.cos(a))}" y2="${Math.round(100 + 34 * Math.sin(a))}" stroke="var(--ink)" stroke-width="3" stroke-linecap="round"/>`;
    })
    .join('');
  return svg(
    `<svg viewBox="0 0 330 200" xmlns="http://www.w3.org/2000/svg">` +
      `<circle cx="${cx}" cy="${cy}" r="${R}" fill="none" stroke="var(--ink-soft)" stroke-width="2" stroke-dasharray="6 6"/>` +
      `<circle cx="292" cy="100" r="20" fill="var(--sun)" stroke="var(--ink)" stroke-width="3.5"/>${sunRays}` +
      `<circle cx="${cx}" cy="${cy}" r="22" fill="var(--sky)" stroke="var(--ink)" stroke-width="3.5"/>` +
      `<circle cx="${mx}" cy="${my}" r="${r}" fill="var(--ink-soft)" stroke="var(--ink)" stroke-width="3"/>` +
      `<path d="M ${mx} ${my - r} A ${r} ${r} 0 0 1 ${mx} ${my + r} Z" fill="var(--sun)" stroke="var(--ink)" stroke-width="3"/>` +
      `</svg>`,
    label,
  );
}
