/** くきを 横に 切った 断面の 模式図。ring: 通り道が 輪のように そまる / all: 全体が そまる / none: どこも そまらない */
function stemCut(kind: 'ring' | 'all' | 'none', label: string): Figure {
  const dots = Array.from({ length: 10 }, (_, i) => {
    const a = (i * Math.PI) / 5;
    const x = Math.round(100 + 52 * Math.cos(a));
    const y = Math.round(100 + 52 * Math.sin(a));
    const fill = kind === 'ring' ? 'var(--berry)' : 'var(--white)';
    return `<circle cx="${x}" cy="${y}" r="9" fill="${fill}" stroke="var(--ink)" stroke-width="2"/>`;
  }).join('');
  const body = kind === 'all' ? 'var(--berry)' : 'var(--white)';
  return svg(
    `<svg viewBox="0 0 200 200" xmlns="http://www.w3.org/2000/svg">` +
      `<circle cx="100" cy="100" r="80" fill="${body}" stroke="var(--ink)" stroke-width="3.5"/>` +
      (kind === 'all' ? '' : dots) +
      `</svg>`,
    label,
  );
}
