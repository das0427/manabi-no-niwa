type Band = 'gravel' | 'sand' | 'mud' | 'ash' | 'shell';
const FILL: Record<Band, string> = {
  gravel: 'var(--wood)',
  sand: 'var(--sun)',
  mud: 'var(--wood-dark)',
  ash: 'var(--white)',
  shell: 'var(--sun)',
};
/** 1つの層（x0, y0 から 幅 w・高さ h）の 図形 */
function band(kind: Band, x0: number, y0: number, w: number, h: number): string {
  let s = `<rect x="${x0}" y="${y0}" width="${w}" height="${h}" fill="${FILL[kind]}"/>`;
  if (kind === 'gravel') {
    // 丸い 石: 半径 7、横 28 おき。高さ 36 以上なら 2段（2段めは 14 ずらす）
    const rows = h >= 36 ? [y0 + h / 3, y0 + (2 * h) / 3] : [y0 + h / 2];
    rows.forEach((cy, r) => {
      for (let x = x0 + 14 + (r % 2) * 14; x < x0 + w - 7; x += 28)
        s += `<circle cx="${x}" cy="${Math.round(cy)}" r="7" fill="var(--paper)" stroke="var(--ink)" stroke-width="2"/>`;
    });
  }
  if (kind === 'sand' || kind === 'shell') {
    // 小さな 点: 半径 2、横 14・たて 10 おき
    for (let y = y0 + 6; y < y0 + h - 2; y += 10)
      for (let x = x0 + 7; x < x0 + w - 2; x += 14)
        s += `<circle cx="${x}" cy="${y}" r="2" fill="var(--ink)"/>`;
  }
  if (kind === 'mud') {
    // 細い 横線: 8 おき
    for (let y = y0 + 6; y < y0 + h - 2; y += 8)
      s += `<line x1="${x0 + 4}" y1="${y}" x2="${x0 + w - 4}" y2="${y}" stroke="var(--ink-soft)" stroke-width="1.5"/>`;
  }
  if (kind === 'ash') {
    // とがった 小さな 三角: 横 22 おき、2段
    for (const cy of [y0 + h / 3, y0 + (2 * h) / 3])
      for (let x = x0 + 11; x < x0 + w - 8; x += 22) {
        const y = Math.round(cy);
        s += `<polygon points="${x - 5},${y + 4} ${x},${y - 5} ${x + 5},${y + 4}" fill="var(--ink-soft)"/>`;
      }
  }
  if (kind === 'shell') {
    // 貝: 扇の 形を 2つ
    for (const cx of [x0 + Math.round(w * 0.3), x0 + Math.round(w * 0.7)]) {
      const cy = Math.round(y0 + h / 2 + 6);
      s += `<path d="M ${cx - 10} ${cy} A 10 10 0 0 1 ${cx + 10} ${cy} Z" fill="var(--white)" stroke="var(--ink)" stroke-width="2"/>`;
    }
  }
  s += `<line x1="${x0}" y1="${y0 + h}" x2="${x0 + w}" y2="${y0 + h}" stroke="var(--ink)" stroke-width="2.5"/>`;
  return s;
}
const frame =
  '<rect x="10" y="10" width="280" height="160" fill="none" stroke="var(--ink)" stroke-width="3.5"/>';
/** がけの 断面（上から 下の じゅんに 層を 書く。層の 高さは 等分） */
function layers(bands: Band[], label: string): Figure {
  const h = 160 / bands.length;
  const body = bands
    .map((b, i) => band(b, 10, Math.round(10 + i * h), 280, Math.round(h)))
    .join('');
  return svg(
    `<svg viewBox="0 0 300 180" xmlns="http://www.w3.org/2000/svg">${body}${frame}</svg>`,
    label,
  );
}
/** 断層の 模式図: 左と 右で 同じ 層の ならびが 半分 ずれて いる */
function fault(label: string): Figure {
  const left = [
    ['sand', 40],
    ['mud', 40],
    ['gravel', 40],
    ['sand', 40],
  ] as const;
  const right = [
    ['sand', 60],
    ['mud', 40],
    ['gravel', 40],
    ['sand', 20],
  ] as const;
  let y = 10;
  let body = '';
  for (const [b, h] of left) {
    body += band(b, 10, y, 140, h);
    y += h;
  }
  y = 10;
  for (const [b, h] of right) {
    body += band(b, 150, y, 140, h);
    y += h;
  }
  body += '<line x1="150" y1="10" x2="150" y2="170" stroke="var(--ink)" stroke-width="4"/>';
  return svg(
    `<svg viewBox="0 0 300 180" xmlns="http://www.w3.org/2000/svg">${body}${frame}</svg>`,
    label,
  );
}
/** つぶの 形（round: 丸い れき / angular: 角ばった 火山灰 / fine: とても 細かい どろ） */
function grains(kind: 'round' | 'angular' | 'fine', label: string): Figure {
  let s =
    '<rect x="4" y="4" width="192" height="92" rx="8" fill="var(--paper)" stroke="var(--ink)" stroke-width="3"/>';
  if (kind === 'round')
    for (const [cx, cy, rx, ry] of [
      [40, 50, 18, 14],
      [80, 32, 14, 11],
      [118, 60, 20, 15],
      [158, 38, 15, 12],
      [160, 74, 12, 10],
    ])
      s += `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="var(--wood)" stroke="var(--ink)" stroke-width="3"/>`;
  if (kind === 'angular')
    for (const pts of [
      '22,62 40,26 58,50 48,74',
      '72,40 92,22 104,48 80,58',
      '112,74 124,40 150,62 134,84',
      '150,30 176,20 182,48',
      '60,82 74,62 92,80',
    ])
      s += `<polygon points="${pts}" fill="var(--white)" stroke="var(--ink)" stroke-width="3" stroke-linejoin="miter"/>`;
  if (kind === 'fine')
    for (let y = 16; y < 90; y += 9)
      for (let x = 14; x < 190; x += 9)
        s += `<circle cx="${x}" cy="${y}" r="2" fill="var(--wood-dark)"/>`;
  return svg(`<svg viewBox="0 0 200 100" xmlns="http://www.w3.org/2000/svg">${s}</svg>`, label);
}

