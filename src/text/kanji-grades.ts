/** 学年 → その学年に配当された漢字を連結した文字列。 */
export const KANJI_BY_GRADE: Record<1 | 2 | 3 | 4 | 5 | 6, string> = {
  1: G1.join(''),
  2: G2.join(''),
  3: G3.join(''),
  4: G4.join(''),
  5: G5.join(''),
  6: G6.join(''),
};

export type KanjiGrade = 1 | 2 | 3 | 4 | 5 | 6 | 7;

const GRADE_OF: ReadonlyMap<string, KanjiGrade> = (() => {
  const m = new Map<string, KanjiGrade>();
  for (const g of [1, 2, 3, 4, 5, 6] as const) {
    for (const ch of KANJI_BY_GRADE[g]) m.set(ch, g);
  }
  return m;
})();

/**
 * 漢字 1 字の配当学年。配当表に無い字（中学校以降の漢字・漢字でない字）は 7。
 * 2 字以上を渡したときは先頭の 1 字（コードポイント単位）だけを見る。空文字は 7。
 */
export function kanjiGrade(ch: string): KanjiGrade {
  const first = ch.codePointAt(0);
  if (first === undefined) return 7;
  return GRADE_OF.get(String.fromCodePoint(first)) ?? 7;
}
